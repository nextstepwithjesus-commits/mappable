/**
 * Числа словами Синодального текста (Д6; 04 § 17.2: «каждое число текста стоит в своём стихе вне скобок»).
 *
 * `numberSpans(text)` находит в тексте подряд идущие числительные — количественные и порядковые, в любом падеже
 * («сто восемьдесят два», «в двадцать седьмой год», «шестисотый», «Шестьсот первого») — и даёт их значение и точные слова.
 * По ним шаг D6 берёт слова числа из стиха, а проверка базы сверяет, что число записи действительно стоит в стихе.
 */

const STEMS: [string, number][] = [
  ['одиннадцат', 11], ['двенадцат', 12], ['тринадцат', 13], ['четырнадцат', 14], ['пятнадцат', 15], ['шестнадцат', 16],
  ['семнадцат', 17], ['восемнадцат', 18], ['девятнадцат', 19],
  ['двадцат', 20], ['тридцат', 30], ['сороков', 40], ['сорок', 40], ['пятьдесят', 50], ['пятидесят', 50], ['шестьдесят', 60],
  ['шестидесят', 60], ['семьдесят', 70], ['семидесят', 70], ['восемьдесят', 80], ['восьмидесят', 80], ['девяност', 90],
  ['двести', 200], ['двухсот', 200], ['триста', 300], ['трехсот', 300], ['четыреста', 400], ['четырехсот', 400],
  ['пятьсот', 500], ['пятисот', 500], ['шестьсот', 600], ['шестисот', 600], ['семьсот', 700], ['семисот', 700],
  ['восемьсот', 800], ['восьмисот', 800], ['девятьсот', 900], ['девятисот', 900],
  ['сто', 100], ['ста', 100], ['сот', 100],
  ['десят', 10], ['девят', 9], ['восем', 8], ['восьм', 8], ['седьм', 7], ['сем', 7], ['шест', 6], ['пят', 5],
  ['четверт', 4], ['четыр', 4], ['трет', 3], ['трех', 3], ['трем', 3], ['три', 3], ['втор', 2], ['двух', 2], ['двум', 2],
  ['два', 2], ['две', 2], ['перв', 1], ['один', 1], ['одн', 1],
];
/** Окончания, при которых основа — числительное (иначе «семя», «стал», «пятно» дали бы число). */
const ENDINGS = new Set(['', 'ь', 'и', 'а', 'о', 'е', 'ый', 'ий', 'ой', 'ая', 'ое', 'ого', 'ому', 'ом', 'ую', 'ые', 'ых', 'ым', 'ти', 'ми', 'у']);
/** «третий» склоняется через мягкий знак: третьего, третьей, третья. */
const SOFT = new Set(['ьего', 'ьем', 'ьему', 'ья', 'ью', 'ьи', 'ьей', 'ьих']);

const low = (t: string) => t.toLowerCase().replace(/ё/g, 'е');

/** Значение одного слова-числительного или undefined. */
export function wordValue(token: string): number | undefined {
  const t = low(token);
  for (const [s, v] of STEMS) if (t.startsWith(s) && (ENDINGS.has(t.slice(s.length)) || (s === 'трет' && SOFT.has(t.slice(s.length))))) return v;
  return undefined;
}

export interface NumberSpan { value: number; words: string; start: number; end: number }

/** Подряд идущие числительные текста (через пробел): «сто восемьдесят два» — одно число 182. */
export function numberSpans(text: string): NumberSpan[] {
  const out: NumberSpan[] = [];
  const re = /[А-Яа-яЁё]+/g;
  let cur: NumberSpan | undefined;
  let m: RegExpExecArray | null;
  while ((m = re.exec(text))) {
    const v = wordValue(m[0]);
    const gapOk = cur && /^\s+$/.test(text.slice(cur.end, m.index));
    if (v !== undefined && cur && gapOk) {
      cur.value += v;
      cur.end = m.index + m[0].length;
      cur.words = text.slice(cur.start, cur.end);
      continue;
    }
    if (cur) out.push(cur), (cur = undefined);
    if (v !== undefined) cur = { value: v, words: m[0], start: m.index, end: m.index + m[0].length };
  }
  if (cur) out.push(cur);
  return out;
}

/** Слова числа `n` в тексте (первое вхождение) или undefined. */
export function wordsOf(n: number, text: string): string | undefined {
  return numberSpans(text).find((s) => s.value === n)?.words;
}
