/** Тождество по форме у записей, которые держатся только на форме «выв.» (02 § 3.3.5): idCert и identity … inferred. */
function autoIdCert(base: Base, step: string) {
  const A = actorsOf(base);
  const withInf = [...A.values()].filter((a) => inferredForms(a).length);
  const n = { facts: 0, memberships: 0, nodata: 0, origins: 0 };
  const touched = new Set<string>();
  for (const a of withInf) {
    for (const f of a.facts) {
      if (f.idCert || f.prov?.status === 'quarantine' || f.field === 'scripture') continue;
      const rs = refsDeep(f.value).filter((r) => r);
      const form = rs.length ? restsOnForm(a, rs) : undefined;
      if (form) {
        f.idCert = { form: form.id!, refs: [...new Set(rs)] };
        touch(f, step);
        n.facts++;
        touched.add(a.id);
      }
    }
  }
  for (const m of base.memberships) {
    const a = A.get(m.actor);
    const form = a && !m.idCert && m.refs.length ? restsOnForm(a, m.refs) : undefined;
    if (form) (m.idCert = { form: form.id!, refs: [...m.refs] }), touch(m, step), n.memberships++, touched.add(m.actor);
  }
  for (const x of base.nodata) {
    const a = A.get(x.actor);
    const form = a && !x.idCert && x.refs.length ? restsOnForm(a, x.refs) : undefined;
    if (form) (x.idCert = { form: form.id!, refs: [...x.refs] }), touch(x, step), n.nodata++, touched.add(x.actor);
  }
  for (const o of base.origins) {
    if (o.identity?.degree === 'inferred' || o.candidates?.length) continue;
    for (const [end, of] of [[o.parent, 'parent'], [o.child, 'child']] as const) {
      const a = end ? A.get(end) : undefined;
      if (!a || !inferredForms(a).length) continue;
      const f = restsOnForm(a, o.refs);
      if (!f) continue;
      o.identity = {
        of, degree: 'inferred', form: f.id!, refs: [...new Set([...o.refs, ...(f.compare?.main.refs ?? [])])],
        note: `в стихах ребра ${of === 'parent' ? 'родитель' : 'ребёнок'} назван формой «${f.form}» — формой «выв.» карточки ${mainOf(a).form}: так выходит, если сравнить ${f.compare!.form.refs[0]} и ${f.compare!.main.refs[0]}`,
      } as Origin['identity'];
      touch(o, step);
      n.origins++;
      touched.add(a.id);
      break;
    }
  }
  return {
    what: `Д-15: тождество по форме у записей, которые держатся только на форме «выв.» (все стихи — стихи формы, форма «Писание» в них не стоит): утверждений ${n.facts}, членств ${n.memberships}, «нет сведений» ${n.nodata} — idCert; рёбер ${n.origins} — identity … inferred с номером формы`,
    why: '02 ред. 4.4 § 3.3.5 (тождество по форме у записей; задача К-18)',
    refs: ['1Пар 7:1'],
    actors: [...touched].map((x) => x.slice(2)),
    other: ['origins', 'memberships', 'nodata'],
  };
}
