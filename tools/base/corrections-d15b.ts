/** Новая запись «возможно, то же лицо» уровня «вывод» (02 § 3.11). */
interface Rel { b: string; refs: Ref[]; note: string }

interface Split {
  /** Карточка, с которой уходят формы. */
  from: string;
  /** Новая карточка; при `into` — существующая карточка, куда переходит форма. */
  id: string;
  into?: true;
  sex: 'm' | 'f';
  /** Формы, которые уходят с карточки `from` (их стихи — стихи новой карточки). */
  forms: string[];
  /** Имена новой карточки (по умолчанию — первая форма основная, остальные — как были). */
  names?: Name[];
  disambig?: string;
  roles?: string[];
  prominence?: number;
  /** Стихи, которые тоже принадлежат новой карточке (рассказ о ней без имени). */
  addRefs?: Ref[];
  /** Утверждения новой карточки. */
  facts?: Assertion[];
  /** Утверждения карточки `from`, которые переходят целиком (кроме тех, что переходят по стихам сами). */
  move?: string[];
  /** Утверждения карточки `from`, которые остаются на ней, хотя все их стихи — стихи новой карточки (заметка о тождестве). */
  keep?: string[];
  /** Переписать утверждение (по номеру) — на любой из двух карточек. */
  rewrite?: Record<string, Partial<Assertion> & { value?: Record<string, unknown> }>;
  /** Новые рёбра новой карточки. */
  origins?: Omit<Origin, 'prov'>[];
  srcDisambig?: string;
  srcRoles?: string[] | null;
  rels: Rel[];
}

/** Стихи записи — все ключи `refs` и `ref` на любой глубине. */
function refsDeep(x: unknown): Ref[] {
  const out: Ref[] = [];
  const go = (y: unknown) => {
    if (Array.isArray(y)) return y.forEach(go);
    if (!y || typeof y !== 'object') return;
    const o = y as Record<string, unknown>;
    if (Array.isArray(o.refs)) out.push(...(o.refs as Ref[]).filter((r) => typeof r === 'string'));
    if (typeof o.ref === 'string') out.push(o.ref);
    if (typeof o.first === 'string') out.push(o.first);
    if (Array.isArray(o.key)) out.push(...(o.key as Ref[]));
    for (const [k, z] of Object.entries(o)) if (k !== 'refs' && k !== 'key') go(z);
  };
  go(x);
  return out;
}
const inSet = (refs: Ref[], vs: Set<string>) => verseIds(refs).every((v) => vs.has(v));
const touches = (refs: Ref[], vs: Set<string>) => verseIds(refs).some((v) => vs.has(v));
/** Ссылки, целиком лежащие вне множества стихов. */
const outside = (refs: Ref[], vs: Set<string>) => refs.filter((r) => !verseIds([r]).some((v) => vs.has(v)));
const earliest = (refs: Ref[]) => {
  const order = loadBible().order;
  const idx = new Map(order.map((k, i) => [k, i]));
  return [...refs].sort((a, b) => (idx.get(verseIds([a])[0]) ?? 1e9) - (idx.get(verseIds([b])[0]) ?? 1e9))[0];
};

interface SplitLog { step: string; id: string; moved: string[]; mixed: string[]; origins: string[] }
export const SPLIT_LOG: SplitLog[] = [];

function applySplit(base: Base, sp: Split, step: string, at: string) {
  const A = actorsOf(base);
  const src = A.get(sp.from);
  if (!src) throw new Error(`${step}: нет карточки ${sp.from}`);
  const log: SplitLog = { step, id: sp.id, moved: [], mixed: [], origins: [] };
  // формы и их стихи
  const moved = sp.forms.map((f) => formOf(src, f, step));
  src.names = src.names.filter((n) => !moved.includes(n));
  const refs = [...new Set([...moved.flatMap((n) => n.refs), ...(sp.addRefs ?? [])])];
  const V = new Set(verseIds(refs));
  let dst: Actor;
  if (sp.into) {
    dst = A.get(sp.id)!;
    if (!dst) throw new Error(`${step}: нет карточки ${sp.id}`);
    // та же форма у карточки-цели — только стихи; иначе — форма из `names`
    for (const n of moved) {
      const same = dst.names.find((x) => x.form === n.form);
      if (same) same.refs = [...new Set([...same.refs, ...n.refs])];
    }
    for (const n of sp.names ?? []) dst.names.push(structuredClone(n));
    touch(dst, step);
  } else {
    if (A.has(sp.id)) throw new Error(`${step}: карточка ${sp.id} уже есть`);
    const names: Name[] = sp.names
      ? structuredClone(sp.names)
      : moved.map((n, i) => ({ form: n.form, type: i === 0 ? 'main' : n.type, refs: [...n.refs], ...(i > 0 && n.note ? { note: n.note } : {}) }) as Name);
    dst = {
      id: sp.id, kind: 'human', sex: sp.sex, names, ...(sp.disambig && { disambig: sp.disambig }),
      ...(sp.roles && { roles: sp.roles }), prominence: sp.prominence ?? 1, facts: [], prov: { ...by(step), status: 'draft' },
    } as Actor;
    const vol = volOf(base, sp.from);
    vol.actors.splice(vol.actors.findIndex((a) => a.id === sp.from) + 1, 0, dst);
  }
  // утверждения: целиком по стихам новой карточки — переходят; смешанные — в журнал (правятся явно)
  const srcNames = () => src.names.filter((n) => n.cert !== 'inference');
  const namesSrc = (rs: Ref[]) => verseIds(rs).some((v) => srcNames().some((n) => stands(n.form, v)));
  for (const f of [...src.facts]) {
    if (f.field === 'scripture' || sp.keep?.includes(fid(base, f) ?? '')) continue;
    const rs = refsDeep(f.value);
    const explicit = sp.move?.includes(fid(base, f) ?? '');
    if (explicit || (rs.length && inSet(rs, V))) {
      src.facts = src.facts.filter((x) => x !== f);
      dst.facts.push(touch(f, step));
      log.moved.push(fid(base, f) ?? f.field);
    } else if (rs.length && touches(rs, V) && !sp.rewrite?.[fid(base, f) ?? '']) log.mixed.push(`${fid(base, f)} ${f.field}`);
  }
  for (const f of sp.facts ?? []) dst.facts.push({ ...structuredClone(f), prov: by(step) });
  // переписанные утверждения (на любой из карточек)
  for (const [id, patch] of Object.entries(sp.rewrite ?? {})) {
    const f = [...src.facts, ...dst.facts].find((x) => fid(base, x) === id);
    if (!f) throw new Error(`${step}: нет утверждения ${id} у ${src.id} или ${dst.id}`);
    Object.assign(f, structuredClone(patch));
    if (patch.cert === undefined && 'cert' in patch) delete f.cert;
    touch(f, step);
  }
  // места Писания: у исходной — без стихов новой; у новой — свои
  const sk = src.facts.find((f) => f.field === 'scripture');
  if (sk) {
    const v = sk.value as { first?: string; key?: Ref[] };
    const key = v.key ? outside(v.key, V) : undefined;
    const rest = [...(key ?? []), ...srcNames().flatMap((n) => n.refs)];
    const first = v.first && touches([v.first], V) ? earliest(rest) : v.first;
    sk.value = { ...(first && { first }), ...(key && key.length && { key }) };
    touch(sk, step);
  }
  const dk = dst.facts.find((f) => f.field === 'scripture');
  if (!dk) {
    const all = [...new Set(dst.names.flatMap((n) => n.refs))];
    dst.facts.push({ sec: 23, field: 'scripture', value: { first: earliest(all), ...(all.length > 1 && { key: all }) }, prov: by(step) } as Assertion);
  } else if (sp.into) {
    const v = dk.value as { first?: string; key?: Ref[] };
    const key = [...new Set([...(v.key ?? (v.first ? [v.first] : [])), ...refs])];
    dk.value = { first: earliest(key), key };
    touch(dk, step);
  }
  dst.facts.sort((a, b) => a.sec - b.sec);
  // рёбра: целиком по стихам новой карточки — к ней; смешанные — стихи новой уходят в копию ребра; ребро, у которого не
  // осталось стиха с именем исходной карточки, переходит целиком
  for (const o of [...base.origins]) {
    for (const end of ['parent', 'child'] as const) {
      if (o[end] !== src.id || !touches(o.refs, V)) continue;
      const rest = outside(o.refs, V);
      const key = `${o.child}←${o.parent}`;
      if (!rest.length || !namesSrc(rest)) {
        o[end] = dst.id;
        delete o.identity;
        touch(o, step);
        log.origins.push(`${key}: целиком`);
      } else {
        const take = o.refs.filter((r) => !rest.includes(r));
        o.refs = rest;
        touch(o, step);
        // копия — только если другой конец ребра назван в уходящих стихах (у матери с общими стихами — не назван)
        const otherId = o[end === 'parent' ? 'child' : 'parent'];
        const other = otherId ? A.get(otherId) : undefined;
        if (!other || !verseIds(take).some((v) => other.names.some((n) => stands(n.form, v)))) {
          log.origins.push(`${key}: стихи ${take.join(', ')} сняты`);
          continue;
        }
        const twin = base.origins.find((x) => x !== o && x[end] === dst.id && x[end === 'parent' ? 'child' : 'parent'] === otherId && x.role === o.role);
        if (twin) {
          twin.refs = [...new Set([...twin.refs, ...take])];
          touch(twin, step);
          log.origins.push(`${key}: стихи ${take.join(', ')} — в ребро ${dst.id}`);
          continue;
        }
        const copy: Origin = structuredClone(o);
        delete copy.id;
        delete copy.identity;
        delete (copy as { order?: number }).order;
        copy[end] = dst.id;
        copy.refs = take;
        base.origins.push(touch(copy, step));
        log.origins.push(`${key}: стихи ${take.join(', ')} — к ${dst.id}`);
      }
    }
  }
  for (const o of sp.origins ?? []) base.origins.push({ ...structuredClone(o), prov: by(step) } as Origin);
  // союзы: стихи новой карточки — в союз с ней
  for (const u of [...base.unions]) {
    const end = u.husband === src.id ? 'husband' : u.wife === src.id ? 'wife' : undefined;
    if (!end) continue;
    const terms = u.terms.filter((t) => touches(t.refs, V));
    if (!terms.length) continue;
    const allIn = u.terms.every((t) => inSet(t.refs, V) || !namesSrc(outside(t.refs, V)));
    const other = end === 'husband' ? u.wife : u.husband;
    const id = end === 'husband' ? `u-${dst.id.slice(2)}--${other.slice(2)}` : `u-${other.slice(2)}--${dst.id.slice(2)}`;
    if (allIn) {
      base.unions = base.unions.filter((x) => x !== u);
      base.unions.push(touch({ ...u, id, [end]: dst.id }, step));
    } else {
      const copy = structuredClone(u);
      copy.id = id;
      copy[end] = dst.id;
      copy.terms = terms.map((t) => ({ ...t, refs: t.refs.filter((r) => !outside(t.refs, V).includes(r)) }));
      for (const t of copy.terms) delete t.note;
      for (const t of u.terms) {
        t.refs = outside(t.refs, V);
        if (sp.forms.some((f) => t.note?.includes(f))) delete t.note;
      }
      u.terms = u.terms.filter((t) => t.refs.length);
      touch(u, step);
      base.unions.push(touch(copy, step));
    }
  }
  // «нет сведений»: стихи новой карточки — не стихи исходной
  for (const n of base.nodata) {
    if (n.actor !== src.id) continue;
    if (n.read?.some((r) => touches([r], V))) {
      n.read = outside(n.read, V);
      touch(n, step);
    }
  }
  // уточнение и роли исходной карточки
  if (sp.srcDisambig !== undefined) src.disambig = sp.srcDisambig;
  if (sp.srcRoles === null) delete src.roles;
  else if (sp.srcRoles) src.roles = sp.srcRoles;
  touch(src, step);
  // «возможно, то же лицо»
  for (const r of sp.rels) base.relations.push({ a: dst.id, b: r.b, kind: 'possibly-same', refs: r.refs, cert: 'inference', note: r.note, prov: { ...by(step), status: 'draft' } });
  void at;
  SPLIT_LOG.push(log);
  return dst;
}

