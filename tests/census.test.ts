/** Пересечения кадра вне списка KNOWN_Y11[key] или сверх его числа. */
function unknownCrossings(c: ReturnType<CensusMod['census']>, key: string): string[] {
  const known = KNOWN_Y11[key] ?? {};
  const got = new Map<string, number>();
  for (const q of c.y11list) got.set(q, (got.get(q) ?? 0) + 1);
  // пересборка списков (tools/_i2-known.ts): I2_KNOWN_DUMP=файл — пересечения сцен в порядке прогона теста
  if (process.env.I2_KNOWN_DUMP) {
    const [id, k, w] = key.split('|');
    appendFileSync(process.env.I2_KNOWN_DUMP, [`== ${id} ×${k} ${w}: y11trails ${c.y11trails}`, ...[...got].sort().map(([q, n]) => `  ${n} ${q}`)].join('\n') + '\n');
  }
  return [...got].filter(([q, n]) => n > (known[q]?.[0] ?? 0)).map(([q, n]) => `${q} ×${n}`);
}
/** Я1 и постороннее лицо Я14 кадра не на известных путях KNOWN_Y1[key] (сцены без списка — прежние пороги strict). */
function unknownY1(c: ReturnType<CensusMod['census']>, key: string): string[] {
  const known = KNOWN_Y1[key];
  if (!known) return [];
  const bad = c.issues.filter((q) => (q.check === 'Я1' || (q.check === 'Я14' && q.text.startsWith('постороннее'))) && !(q.ks in known)).map((q) => `${q.check} ${q.ks}: ${q.text}`);
  // концы Я14 — не ниже прежнего порога, кроме точек на известных путях
  const off = c.issues.filter((q) => q.check === 'Я14' && !q.text.startsWith('постороннее') && !(q.ks in known)).length;
  if (c.y14of && (c.y14of - off) / c.y14of < 0.95 && off > 0) bad.push(`Я14: концы не названы в ${off} точках вне известных путей`);
  return bad;
}

