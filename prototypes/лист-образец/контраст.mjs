// Скрипт контраста (08 § 3.1, § 3.2): все пары из токены.json → $extensions["app.контраст"]
// в обеих темах; пары цвета действия — для своего варианта. Код выхода 1, если пара ниже нормы.
// Запуск из корня: node prototypes/лист-образец/контраст.mjs
// ПРОТОТИП: в продукт не переносится.
import { pathToFileURL } from 'node:url';
import { загрузить, плоско, разрешить, hex, контраст } from './токены.mjs';

const НОРМА = { текст: 4.5, графика: 3, украшение: 1 };
const ТЕМЫ = [['светлая', []], ['тёмная', ['тёмная']]];

export function отчёт() {
  const док = загрузить();
  const все = плоско(док);
  const пары = док.$extensions['app.контраст'];
  const строки = [];
  for (const [вид, список] of Object.entries(пары)) {
    if (вид.startsWith('$')) continue;
    for (const [f, b, примечание = ''] of список) {
      for (const [тема, режим] of ТЕМЫ) {
        if (примечание === 'только тёмная' && тема !== 'тёмная') continue;
        // кант Мф/Лк в тёмной теме не рисуется: лента без канта, считается лента
        // контур категориальных цветов в тёмной теме не обязателен: считается заливка к фону
        let fg = `цвет.${f}`, bg = `цвет.${b}`, прим = примечание;
        if (тема === 'тёмная' && f.startsWith('кат-')) { bg = 'цвет.фон'; прим = 'тёмная: заливка к фону, без контура'; }
        const a = hex(разрешить(все, fg, режим)), c = hex(разрешить(все, bg, режим));
        const k = контраст(a, c);
        строки.push({ вид, f, b: bg.slice(5), тема, a, c, k: Math.round(k * 100) / 100, норма: НОРМА[вид], ок: k + 1e-9 >= НОРМА[вид], прим });
      }
    }
  }
  return строки;
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  const с = отчёт();
  const плохие = с.filter((x) => !x.ок);
  const fmt = (n) => n.toFixed(2).replace('.', ',');
  for (const вид of ['текст', 'графика', 'украшение']) {
    const г = с.filter((x) => x.вид === вид);
    const худ = г.reduce((m, x) => (x.k < m.k ? x : m), г[0]);
    console.log(`${вид}: пар ${г.length}, норма ${fmt(НОРМА[вид])}, худшая ${худ.f} к ${худ.b} (${худ.тема}) — ${fmt(худ.k)}`);
  }
  if (плохие.length) {
    console.log(`НИЖЕ НОРМЫ: ${плохие.length}`);
    for (const x of плохие) console.log(`  ${x.f} к ${x.b} (${x.тема}): ${fmt(x.k)} < ${fmt(x.норма)}`);
    process.exit(1);
  }
  console.log(`пар ниже нормы: 0 из ${с.length}`);
}
