/**
 * Отчёты «Предки» и «Потомки» (03 § 18) и таблица CSV (03 § 22.3). Без DOM.
 * - одно прочтение — текущее; кровные рёбра «сказано» и «вывод»; `parents-word`, приёмные и толкования номера не получают;
 * - Ahnentafel: 2N — отец, 2N + 1 — мать, только по кровному ребру; считается `BigInt`, хранится строкой; лицо на нескольких
 *   путях стоит один раз — под наименьшим номером, остальные номера — «ещё пути»; шаг «из сыновей» номер не получает —
 *   нумерация кончается, дальше своя группа с номерами от 1;
 * - д’Абовиль: 1, 1.1, 1.2, 1.2.1… в порядке текста; мать — в каждой строке; «Потомков дальше» — за пределом поколений.
 */
import type { Граф, Выбор, Ребро } from './граф.ts';
import { словоСоюза } from './лес.ts';

export interface СтрокаПредка {
  номер: string;
  порядок: number;
  поколение: number;
  лицо: number;
  основание: 'лицо' | 'отец' | 'мать';
  ребро?: number;
  /** Другие номера того же лица (потеря предков). */
  ещё: string[];
  /** Шаг по тексту не меньше 1 (пропуск поколений на пути). */
  пропуск: boolean;
}
export interface Предки { лицо: number; группы: { заголовок: string; строки: СтрокаПредка[] }[]; лиц: number; номеров: number; поколений: number; естьПропуск: boolean; выбор: Выбор }

export function предки(г: Граф, лицо: number, выбор: Выбор = {}, предел = 200_000): Предки {
  const к = г.кровь(выбор);
  const группы: Предки['группы'] = [];
  let номеров = 0, поколений = 0, естьПропуск = false;
  const всего = new Set<number>();
  const очередьГрупп: { корень: number; заголовок: string }[] = [{ корень: лицо, заголовок: 'Предки по кровным рёбрам' }];
  const былКорнем = new Set<number>();
  while (очередьГрупп.length) {
    const { корень, заголовок } = очередьГрупп.shift()!;
    if (былКорнем.has(корень)) continue;
    былКорнем.add(корень);
    const строки = new Map<number, СтрокаПредка>();
    let слой: { p: number; n: bigint; e?: number; осн: СтрокаПредка['основание']; пр: boolean }[] = [{ p: корень, n: 1n, осн: 'лицо', пр: false }];
    let gen = 0;
    while (слой.length && номеров < предел) {
      слой.sort((a, b) => (a.n < b.n ? -1 : a.n > b.n ? 1 : 0));
      const след: typeof слой = [];
      for (const x of слой) {
        номеров++;
        const есть = строки.get(x.p);
        if (есть) { есть.ещё.push(x.n.toString()); } else строки.set(x.p, { номер: x.n.toString(), порядок: 0, поколение: gen, лицо: x.p, основание: x.осн, ...(x.e !== undefined && { ребро: x.e }), ещё: [], пропуск: x.пр });
        const f = к.отец[x.p], m = к.мать[x.p];
        if (f >= 0) след.push({ p: г.рёбра[f].род, n: 2n * x.n, e: f, осн: 'отец', пр: x.пр || г.рёбра[f].пропуск });
        if (m >= 0) след.push({ p: г.рёбра[m].род, n: 2n * x.n + 1n, e: m, осн: 'мать', пр: x.пр || г.рёбра[m].пропуск });
        // кровного отца нет, есть «из сыновей» — нумерация кончается, дальше своя группа (03 § 18.1)
        if (f < 0 && к.предок[x.p] >= 0) {
          const e = г.рёбра[к.предок[x.p]];
          очередьГрупп.push({ корень: e.род, заголовок: `Через ребро «из сыновей» от: ${г.полное(x.p)} (${e.стихи[0] ?? ''}) — число поколений не названо` });
          естьПропуск = true;
        }
      }
      if (след.length) gen++;
      слой = след;
    }
    поколений = Math.max(поколений, gen);
    const list = [...строки.values()];
    list.forEach((s, i) => { s.порядок = i + 1; if (s.пропуск) естьПропуск = true; всего.add(s.лицо); });
    группы.push({ заголовок, строки: list });
  }
  всего.delete(лицо);
  return { лицо, группы, лиц: всего.size, номеров, поколений, естьПропуск, выбор };
}

export interface СтрокаПотомка {
  номер: string;
  порядок: number;
  поколение: number;
  лицо: number;
  ребро?: number;
  мать: number;
  союз: string;
  дальше: number;
}
export interface Потомки { лицо: number; строки: СтрокаПотомка[]; изСыновей: number[]; поколений: number; выбор: Выбор }

export function потомки(г: Граф, лицо: number, выбор: Выбор = {}, поколенийНе = Infinity): Потомки {
  const строки: СтрокаПотомка[] = [];
  const был = new Set<number>([лицо]);
  let макс = 0;
  const всеПотомки = (p: number): number => {
    const seen = new Set<number>();
    const st = [p];
    while (st.length) { const x = st.pop()!; for (const e of г.детиКрови(x, выбор)) if (!seen.has(e.реб)) { seen.add(e.реб); st.push(e.реб); } }
    return seen.size;
  };
  const обход = (p: number, номер: string, gen: number, e?: Ребро) => {
    const дети = г.детиКрови(p, выбор).filter((x) => !был.has(x.реб));
    const мать = e ? г.мать(e.реб, выбор) : -1;
    const отец = e && e.роль === 'f' ? e.род : -1;
    const un = мать >= 0 && отец >= 0 ? г.союзы.find((u) => u.муж === отец && u.жена === мать) : undefined;
    const строка: СтрокаПотомка = { номер, порядок: строки.length + 1, поколение: gen, лицо: p, ...(e && { ребро: e.i }), мать, союз: un ? словоСоюза(un.виды) : '', дальше: 0 };
    строки.push(строка);
    макс = Math.max(макс, gen);
    if (gen >= поколенийНе) { строка.дальше = всеПотомки(p); return; }
    let k = 0;
    for (const d of дети) {
      if (был.has(d.реб)) continue;
      был.add(d.реб);
      обход(d.реб, `${номер}.${++k}`, gen + 1, d);
    }
  };
  обход(лицо, '1', 0);
  const к = г.кровь(выбор);
  const изСыновей = г.вниз[лицо].map((i) => г.рёбра[i]).filter((e) => к.предок[e.реб] === e.i).map((e) => e.реб);
  return { лицо, строки, изСыновей, поколений: макс, выбор };
}

// ---------- CSV (03 § 22.3; 08 § 16.5: «;», UTF-8 с BOM) ----------

const поле = (v: string | number) => {
  const s = String(v);
  return /[;"\r\n]/.test(s) ? `"${s.replace(/"/g, '""')}"` : s;
};
export const csv = (rows: (string | number)[][]) => '﻿' + rows.map((r) => r.map(поле).join(';')).join('\r\n') + '\r\n';
/** Номер — текстом со знаком «№» впереди: Excel не разбирает его как число или дату (03 § 22.3). */
export const номерТекстом = (n: string) => `№${n}`;

function описаниеПрочтения(г: Граф, выбор: Выбор): string {
  return [...г.наборы.values()].filter((н) => выбор[н.id] && выбор[н.id] !== н.поУмолчанию).map((н) => `${н.название}: ${н.прочтения.find((p) => p.id === выбор[н.id])?.название}`).join('; ') || 'по умолчанию';
}

export function csvПредков(г: Граф, о: Предки): string {
  const rows: (string | number)[][] = [['№ (Ahnentafel)', 'порядок', 'группа', 'поколение', 'имя', 'уточнение', 'пол', 'основание номера', 'отец', 'мать', 'стихи ребра', 'уровень', 'по словам', 'прочтение', 'номер записи лица', 'номер записи ребра', 'ещё пути']];
  const к = г.кровь(о.выбор);
  о.группы.forEach((гр, gi) => {
    for (const s of гр.строки) {
      const e = s.ребро !== undefined ? г.рёбра[s.ребро] : undefined;
      const л = г.лица[s.лицо];
      rows.push([номерТекстом(s.номер), s.порядок, gi + 1, s.поколение, л.имя, л.уточнПолн ?? '', л.пол ?? '', s.основание, к.отец[s.лицо] >= 0 ? г.имя(г.рёбра[к.отец[s.лицо]].род) : '', к.мать[s.лицо] >= 0 ? г.имя(г.рёбра[к.мать[s.лицо]].род) : 'мать не названа', e?.стихи.join('; ') ?? '', e ? Граф_уровень(e.уровень) : '', e?.поСловам?.l ?? '', описаниеПрочтения(г, о.выбор), `p-${л.id}`, e?.номер ?? '', s.ещё.map(номерТекстом).join(' ')]);
    }
  });
  return csv(rows);
}

export function csvПотомков(г: Граф, о: Потомки): string {
  const rows: (string | number)[][] = [['№ (д’Абовиль)', 'порядок', 'поколение', 'имя', 'уточнение', 'пол', 'мать (союз)', 'стихи ребра', 'уровень', 'по словам', 'прочтение', 'потомков дальше', 'номер записи лица', 'номер записи ребра']];
  for (const s of о.строки) {
    const e = s.ребро !== undefined ? г.рёбра[s.ребро] : undefined;
    const л = г.лица[s.лицо];
    const мать = s.поколение === 0 ? '' : s.мать >= 0 ? `${г.имя(s.мать)}${s.союз ? `, ${s.союз}` : ''}` : 'мать не названа';
    rows.push([номерТекстом(s.номер), s.порядок, s.поколение, л.имя, л.уточнПолн ?? '', л.пол ?? '', мать, e?.стихи.join('; ') ?? '', e ? Граф_уровень(e.уровень) : '', e?.поСловам?.l ?? '', описаниеПрочтения(г, о.выбор), s.дальше, `p-${л.id}`, e?.номер ?? '']);
  }
  for (const p of о.изСыновей) rows.push(['', '', '', г.имя(p), г.лица[p].уточнПолн ?? '', г.лица[p].пол ?? '', `из сыновей: ${г.имя(о.лицо)}`, '', '', '', '', '', `p-${г.лица[p].id}`, '']);
  return csv(rows);
}

const Граф_уровень = (u: string) => (u === 'scripture' ? 'сказано' : u === 'inference' ? 'вывод — так выходит, если сравнить места Библии' : u);

/** Источник ребра одной строкой для «Копировать источник» (03 § 21.2): адрес, уровень, номер записи, ссылка на лист. */
export function источникРебра(г: Граф, e: Ребро, адресЛиста: string): string {
  const кто = `${г.полное(e.род)} — ${e.роль === 'f' ? 'отец' : 'мать'}: ${г.полное(e.реб)}`;
  const слова = e.слова?.length ? ` «${e.слова[0].t}» (${e.слова[0].r})` : '';
  return `${кто}.${слова} Стихи: ${e.стихи.join('; ')}. Уровень: ${Граф_уровень(e.уровень)}${e.поСловам ? `; ${e.поСловам.l} (${e.поСловам.r})` : ''}. Запись ${e.номер}. ${адресЛиста}`;
}
