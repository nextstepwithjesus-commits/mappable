/**
 * Таблица переходов «вид узла × клавиша» для вида «Семья» (03 § 7.3; доступность ред. 4, 4-2): каждая клетка ведёт к предмету,
 * даёт действие или объявление — молчания нет. Фокус ведётся по номеру предмета (09 § 3.2.3). Без DOM.
 * Строки обзора, косы, «Предков и потомков» и «Только отобранных» — вне шага 2.0 (эти виды строятся в пакете 2).
 */
import type { Лес } from './лес.ts';
import type { Геометрия, Предмет } from './раскладка.ts';
import { idЛица } from './раскладка.ts';
import type { Раскрыто } from './семья.ts';

export type Клавиша = 'ArrowUp' | 'ArrowDown' | 'ArrowLeft' | 'ArrowRight' | 'Home' | 'End' | 'Enter';
export const КЛАВИШИ: Клавиша[] = ['ArrowUp', 'ArrowDown', 'ArrowLeft', 'ArrowRight', 'Home', 'End', 'Enter'];

export type Действие = 'выбрать' | 'раскрыть-слот' | 'раскрыть-группу' | 'показать-детей' | 'показать-родителей' | 'перелёт' | 'лист-ребра';
export interface Итог { к?: string; объявить?: string; действие?: Действие }

export interface Контекст { л: Лес; г: Геометрия; раскрыто: Раскрыто }

/** Главный предмет узла: глава блока, отсыл жены или группа. */
export function главный(к: Контекст, узел: number): Предмет | undefined {
  const u = к.л.узлы[узел];
  const id = u.вид === 'block' ? idЛица(к.л, u.лица[0]) : u.вид === 'wife-ref' ? `г-жена-${к.л.граф.лица[u.лица[0]].id}` : `г-группа-${к.л.граф.лица[u.лица[0]].id}`;
  const i = к.г.поИд.get(id);
  return i === undefined ? undefined : к.г.предметы[i];
}
const найти = (к: Контекст, f: (p: Предмет) => boolean) => к.г.предметы.find(f);
const виден = (к: Контекст, узел: number) => к.раскрыто.has(узел);

/** Группа детей, где стоит узел: видимые узлы того же родителя и того же слота (лица «по другому прочтению» — своей группой). */
export function группаДетей(к: Контекст, узел: number): number[] {
  const u = к.л.узлы[узел];
  if (u.родитель < 0 || !виден(к, u.родитель)) return [узел];
  const чтение = u.чтение !== undefined;
  return к.л.узлы[u.родитель].дети.filter((c) => виден(к, c) && к.л.узлы[c].слот === u.слот && (к.л.узлы[c].чтение !== undefined) === чтение);
}

function кРодителям(к: Контекст, узел: number): Итог {
  const { л } = к;
  const u = л.узлы[узел];
  if (u.родитель < 0) return { объявить: 'В этих стихах родители не названы' };
  if (!виден(к, u.родитель)) {
    const p = найти(к, (x) => x.вид === 'родители' && x.узел === узел);
    return p ? { к: p.id, объявить: 'Родители не показаны. Показать — Enter' } : { объявить: 'Родители не показаны' };
  }
  const par = л.узлы[u.родитель];
  if (par.вид === 'group') return { к: главный(к, par.key)?.id };
  if (u.слот >= 100) return { к: idЛица(л, par.лица[u.слот - 100]) }; // мать в блоке (Иисус Христос — к Марии)
  if (u.слот >= 1) {
    const s = найти(к, (x) => x.вид === 'союз' && x.узел === par.key && x.слот === u.слот);
    if (s) return { к: s.id };
  }
  return { к: idЛица(л, par.лица[0]) };
}

function кДетямСлота(к: Контекст, узел: number, слот: number, пусто: string): Итог {
  const { л } = к;
  const дети = л.узлы[узел].дети.filter((c) => л.узлы[c].слот === слот || (слот >= 1 && слот < 100 && л.узлы[c].слот === 100 + слот));
  const вид = дети.filter((c) => виден(к, c));
  if (вид.length) return { к: главный(к, вид[0])?.id };
  if (дети.length) return { объявить: 'Дети не показаны. Показать — Enter на точке союза' };
  return { объявить: пусто };
}

function соседи(к: Контекст, узел: number, клавиша: Клавиша): Итог {
  const гр = группаДетей(к, узел);
  const i = гр.indexOf(узел);
  const j = клавиша === 'ArrowLeft' ? i - 1 : клавиша === 'ArrowRight' ? i + 1 : клавиша === 'Home' ? 0 : гр.length - 1;
  if (гр.length === 1) return { объявить: 'Других детей в этой группе не показано' };
  if (j < 0) return { объявить: 'Первый в этой группе детей' };
  if (j >= гр.length) return { объявить: 'Последний в этой группе детей' };
  if (j === i) return { объявить: клавиша === 'Home' ? 'Первый в этой группе детей' : 'Последний в этой группе детей' };
  return { к: главный(к, гр[j])?.id };
}

export function перейти(к: Контекст, p: Предмет, кл: Клавиша): Итог {
  const { л } = к;
  const u = л.узлы[p.узел];
  const горизонталь = кл === 'ArrowLeft' || кл === 'ArrowRight' || кл === 'Home' || кл === 'End';
  switch (p.вид) {
    case 'лицо': {
      const жена = u.лица.indexOf(p.лицо);
      if (жена > 0) {
        if (кл === 'ArrowUp') {
          const ref = найти(к, (x) => x.вид === 'отсыл-жены' && x.лицо === p.лицо);
          if (ref) return { к: ref.id };
          const отец = л.родитель[p.лицо];
          return отец >= 0 ? { объявить: `Её родители стоят в своей семье. Отец: ${л.граф.имя(отец)}` } : { объявить: 'В этих стихах её родители не названы' };
        }
        if (кл === 'ArrowDown') return кДетямСлота(к, p.узел, жена, 'Детей этого союза в стихах не названо');
        if (кл === 'ArrowLeft') return { к: idЛица(л, u.лица[0]) };
        if (кл === 'ArrowRight') return кДетямСлота(к, p.узел, жена, 'Детей этого союза в стихах не названо');
        if (кл === 'Home' || кл === 'End') return { объявить: 'Home и End ведут по братьям и сёстрам; у жены — стрелки к мужу и детям' };
        return { действие: 'выбрать' };
      }
      if (кл === 'ArrowUp') return кРодителям(к, p.узел);
      if (кл === 'ArrowDown') {
        const s = найти(к, (x) => (x.вид === 'союз' || x.вид === 'мать-не-названа') && x.узел === p.узел);
        if (s) return { к: s.id };
        const вид = u.дети.filter((c) => виден(к, c));
        if (вид.length) return { к: главный(к, вид[0])?.id };
        const ещё = найти(к, (x) => x.вид === 'ещё' && x.узел === p.узел);
        if (ещё) return { к: ещё.id, объявить: 'Дети не показаны. Показать — Enter' };
        return { объявить: 'Детей в этих стихах не названо' };
      }
      if (горизонталь) return соседи(к, p.узел, кл);
      return { действие: 'выбрать' };
    }
    case 'союз':
      if (кл === 'ArrowUp' || кл === 'ArrowLeft') return { к: idЛица(л, u.лица[0]) };
      if (кл === 'ArrowRight') return { к: idЛица(л, p.лицо) };
      if (кл === 'ArrowDown') return кДетямСлота(к, p.узел, p.слот!, 'Детей этого союза в стихах не названо');
      if (кл === 'Home' || кл === 'End') return { объявить: 'Союз: стрелка влево — муж, вправо — жена, вниз — дети' };
      return { действие: 'раскрыть-слот' };
    case 'мать-не-названа':
      if (кл === 'ArrowUp') return { к: idЛица(л, u.лица[0]) };
      if (кл === 'ArrowDown') return кДетямСлота(к, p.узел, -1, 'Детей без названной матери нет');
      if (кл === 'ArrowRight' || кл === 'ArrowLeft') {
        const s = найти(к, (x) => x.вид === 'союз' && x.узел === p.узел);
        return s ? { к: s.id } : { объявить: 'Других союзов у отца нет' };
      }
      if (кл === 'Home' || кл === 'End') return { объявить: 'Группа детей: мать не названа' };
      return { действие: 'раскрыть-слот' };
    case 'группа':
      if (кл === 'ArrowUp') return кРодителям(к, p.узел);
      if (кл === 'ArrowDown') {
        const вид = u.дети.filter((c) => виден(к, c));
        return вид.length ? { к: главный(к, вид[0])?.id } : { объявить: 'Список свёрнут. Раскрыть — Enter' };
      }
      if (горизонталь) return соседи(к, p.узел, кл);
      return { действие: 'раскрыть-группу' };
    case 'отсыл-жены':
      if (кл === 'ArrowUp') return кРодителям(к, p.узел);
      if (кл === 'ArrowDown') return { объявить: 'Отсыл: Enter переводит к ней, к мужу' };
      if (горизонталь) return соседи(к, p.узел, кл);
      return { действие: 'перелёт' };
    case 'ещё':
      if (кл === 'ArrowUp') return { к: idЛица(л, u.лица[0]) };
      if (кл === 'Enter') return { действие: 'показать-детей' };
      return { объявить: `Скрыто детей: ${p.n}. Показать — Enter` };
    case 'родители':
      if (кл === 'ArrowDown') return { к: idЛица(л, u.лица[0]) };
      if (кл === 'Enter') return { действие: 'показать-родителей' };
      return { объявить: 'Родители не показаны. Показать — Enter' };
    case 'отсыл': {
      if (кл === 'ArrowUp') return { к: idЛица(л, p.отсыл!.у) };
      if (кл === 'Enter') return { действие: 'перелёт' };
      if (кл === 'ArrowDown') return { объявить: 'Отсыл: Enter переводит к другому концу' };
      const свои = к.г.предметы.filter((x) => x.вид === 'отсыл' && x.узел === p.узел);
      const i = свои.indexOf(p);
      const j = кл === 'ArrowLeft' ? i - 1 : кл === 'ArrowRight' ? i + 1 : кл === 'Home' ? 0 : свои.length - 1;
      return j >= 0 && j < свои.length && j !== i ? { к: свои[j].id } : { объявить: 'Других отсылов здесь нет' };
    }
    case 'ярлык': {
      const e = л.граф.рёбра[p.ребро!];
      if (кл === 'ArrowUp') return { к: idЛица(л, e.род) };
      if (кл === 'ArrowDown') return { к: idЛица(л, e.реб) };
      if (кл === 'Enter') return { действие: 'лист-ребра' };
      return { объявить: 'Ярлык ребра: Enter открывает лист ребра' };
    }
  }
}

/** Alt + ← / →: соседний узел по ряду схемы через границу семьи (03 § 7.3). */
export function поРяду(к: Контекст, p: Предмет, вправо: boolean): Итог {
  const { л, г } = к;
  const мой = г.узлы.get(p.узел);
  if (!мой) return { объявить: 'Нет соседа' };
  const ряд = [...г.узлы].filter(([k, x]) => x.y === мой.y && л.узлы[k].вид !== 'group').sort((a, b) => a[1].x - b[1].x).map(([k]) => k);
  const i = ряд.indexOf(p.узел);
  const j = вправо ? i + 1 : i - 1;
  if (j < 0 || j >= ряд.length) return { объявить: вправо ? 'Дальше в этом ряду никого' : 'Левее в этом ряду никого' };
  const n = ряд[j];
  const t = главный(к, n);
  const другая = л.узлы[n].родитель !== л.узлы[p.узел].родитель;
  const род = л.узлы[n].родитель >= 0 ? л.граф.имя(л.узлы[л.узлы[n].родитель].лица[0]) : '';
  return { к: t?.id, ...(другая && { объявить: род ? `Другая семья. Родитель: ${род}` : 'Другая семья' }) };
}

/** Буквы: поиск по первым буквам среди раскрытых лиц по порядку леса, от фокуса вперёд (03 § 7.3; 4-13). */
export function поБукве(к: Контекст, p: Предмет | undefined, буква: string): Итог {
  const лица = к.г.предметы.filter((x) => x.вид === 'лицо').sort((a, b) => к.л.порядок[a.узел] - к.л.порядок[b.узел] || a.x - b.x);
  const b = буква.toLocaleLowerCase('ru');
  const start = p ? лица.findIndex((x) => x.id === p.id) : -1;
  for (let k = 1; k <= лица.length; k++) {
    const x = лица[(start + k + лица.length) % лица.length];
    if (к.л.граф.имя(x.лицо).toLocaleLowerCase('ru').startsWith(b)) return { к: x.id };
  }
  return { объявить: `Нет имён на «${буква.toLocaleUpperCase('ru')}»` };
}
