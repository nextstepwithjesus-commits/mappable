/**
 * Слова родства для доступного имени узла: «отношение к выбранному» (03 § 7.4) — только ближняя семья (08 § 4.4: мать, отец,
 * сын, дочь, брат, сестра, муж, жена, дед, бабушка, внук, внучка). Без падежей: слово стоит после тире. Без DOM.
 */
import type { Граф } from './граф.ts';
import type { Лес } from './лес.ts';

const по = (г: Граф, i: number, м: string, ж: string, н: string) => (г.лица[i].пол === 'm' ? м : г.лица[i].пол === 'f' ? ж : н);

export function отношение(г: Граф, _л: Лес, выбрано: number, b: number): string {
  const к = г.кровь({});
  const отец = (x: number) => (к.отец[x] >= 0 ? г.рёбра[к.отец[x]].род : -1);
  const мать = (x: number) => (к.мать[x] >= 0 ? г.рёбра[к.мать[x]].род : -1);
  const родители = (x: number) => [отец(x), мать(x)].filter((y) => y >= 0);
  if (родители(выбрано).includes(b)) return по(г, b, 'отец', 'мать', 'родитель');
  if (родители(b).includes(выбрано)) return по(г, b, 'сын', 'дочь', 'ребёнок');
  for (const u of г.союзыЛица[выбрано]) {
    const un = г.союзы[u];
    if (un.муж === b) return 'муж';
    if (un.жена === b) return 'жена';
  }
  if (г.братья(выбрано).includes(b)) return по(г, b, 'брат', 'сестра', 'брат или сестра');
  if (родители(выбрано).some((p) => родители(p).includes(b))) return по(г, b, 'дед', 'бабушка', 'дед или бабушка');
  if (родители(b).some((p) => родители(p).includes(выбрано))) return по(г, b, 'внук', 'внучка', 'внук или внучка');
  return '';
}
