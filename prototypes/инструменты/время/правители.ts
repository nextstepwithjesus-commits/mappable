/**
 * «Правители» по стихам (04 § 15; решение координатора П-1): номер года царя считается **по стиху синхронизма**, а не от
 * начала царствования в базе. Год воцарения царя K = год N царя X из стиха воцарения K («В тридцать восьмой год Азарии…
 * воцарился Захария», 4 Цар 15:8). Остальные синхронизмы и длины царствований — проверки: выполнен, «до года» (счёт года
 * воцарения) или «напряжение» со стихами. Номер года никогда не больше числа лет по стиху. Без DOM: тест — в CI.
 *
 * Данные — входы Д6 (`chrono.inputs`: `reign` с единицей, `synchronism` с `atYear`). Чего в базе нет и что прототип берёт
 * из стихов сам (задачи данных — в README): короткая форма имени в стихе воцарения («Азария», 4 Цар 15:1) и события народов
 * (4 Цар 18:9, 13).
 */
import type { Chrono } from '../общее/типы.ts';

export type Царство = 'Иудея' | 'Израиль';
export interface Царь {
  id: string;
  имя: string;
  царство: Царство;
  /** Год воцарения на общей оси счёта (0 — первый год Азарии). */
  от: number;
  /** Лет по стиху (у царствований в месяцах — 0: один год счёта). */
  лет: number;
  месяцев?: number;
  стихЛет?: string;
  стихВоцарения?: string;
  /** Синхронизм, которым царь поставлен на ось. */
  по?: Синхронизм;
}
/** Синхронизм: «свой» год царя `кто` (1 — воцарение) = год `год` царя `с` (4 Цар 15:8; 18:9 — «в четвертый год… то есть в седьмой год…»). */
export interface Синхронизм { кто: string; свой: number; с: string; год: number; стих: string }
export type Статус = 'выполнен' | 'до года' | 'напряжение';
export interface Проверка { текст: string; стихи: string[]; статус: Статус; разница: number }
export interface Событие { год: number; текст: string; стих: string; царь?: string }

/** Форма имени в стихе воцарения, где она отличается от имени карточки (база: задача формы имени по стиху, К-18). */
export const ИМЯ_В_СТИХЕ: Record<string, { имя: string; стих: string }> = {
  'p-oziya': { имя: 'Азария', стих: '4Цар 15:1' },
  'p-ieroboam-vtoroy': { имя: 'Иеровоам, сын Иоасов', стих: '4Цар 14:23' },
  'p-osiya-syn-ily': { имя: 'Осия, сын Илы', стих: '4Цар 17:1' },
};
/** События народов со стихом и годом царя (04 § 15.2, строка «Народы»). */
const НАРОДЫ: { царь: string; год: number; текст: string; стих: string }[] = [
  { царь: 'p-ezekiya', год: 4, текст: 'Салманассар, царь Ассирийский, осадил Самарию', стих: '4Цар 18:9' },
  { царь: 'p-ezekiya', год: 6, текст: 'взята Самария', стих: '4Цар 18:10' },
  { царь: 'p-ezekiya', год: 14, текст: 'Сеннахирим, царь Ассирийский, пошёл на города Иудеи', стих: '4Цар 18:13' },
];
/** Цари 4 Цар 15–18. */
export const ЦАРИ = ['p-oziya', 'p-ioafam', 'p-akhaz', 'p-ezekiya', 'p-ieroboam-vtoroy', 'p-zakhariya-syn-ieroboama', 'p-sellum-syn-iavisa', 'p-menaim', 'p-fakiya', 'p-fakey', 'p-osiya-syn-ily'];

const главы = (r: string) => /^4Цар 1[5-8]:/.test(r);

export interface Правители { цари: Царь[]; проверки: Проверка[]; события: Событие[]; синхронизмы: Синхронизм[] }

/** Расчёт по стихам. `имя` — имя карточки (для царей без особой формы в стихе). */
export function правители(chrono: Map<string, Chrono>, имя: (id: string) => string): Правители {
  const лет = new Map<string, { n: number; месяцев?: number; стих: string; царство: Царство }>();
  const синх: Синхронизм[] = [];
  for (const id of ЦАРИ) {
    const c = chrono.get(id)?.chrono;
    if (!c) continue;
    for (const i of c.inputs ?? []) {
      if (i.kind === 'reign' && i.number !== undefined) {
        const царство: Царство = i.kingdom === 'judah' ? 'Иудея' : 'Израиль';
        лет.set(id, i.unit === 'month' ? { n: 0, месяцев: i.number, стих: i.refs[0], царство } : { n: i.number, стих: i.refs[0], царство });
      }
      if (i.kind === 'synchronism' && i.other && i.number !== undefined) синх.push({ кто: id, свой: i.atYear?.number ?? 1, с: i.other, год: i.number, стих: i.refs[0] });
    }
    // прежний вид записи (до Д6): `reign` с `sync`
    for (const r of c.reign ?? []) {
      if (r.over !== 'Иудея' && r.over !== 'Израиль') continue;
      if (!лет.has(id)) лет.set(id, { n: r.years ?? 0, стих: r.refs[0], царство: r.over });
      for (const x of r.sync ?? []) if (!синх.some((y) => y.кто === id && y.стих === x.refs[0])) синх.push({ кто: id, свой: 1, с: x.with, год: x.year, стих: x.refs[0] });
    }
  }
  const от = new Map<string, number>([['p-oziya', 0]]);
  const по = new Map<string, Синхронизм>();
  const воцарение = (id: string) => синх.filter((x) => x.кто === id && x.свой === 1)[0];
  // ставим царя по его стиху воцарения (первый синхронизм воцарения в записи), пока ставится
  for (let круг = 0; круг < 20; круг++) {
    for (const id of лет.keys()) {
      const s0 = воцарение(id);
      if (!s0) continue;
      if (!от.has(id) && от.has(s0.с)) {
        от.set(id, от.get(s0.с)! + s0.год - 1);
        по.set(id, s0);
      }
      if (от.has(id) && !от.has(s0.с) && лет.has(s0.с)) от.set(s0.с, от.get(id)! - s0.год + 1);
    }
  }
  const цари: Царь[] = [...лет]
    .filter(([id]) => от.has(id))
    .map(([id, r]) => ({
      id,
      имя: ИМЯ_В_СТИХЕ[id]?.имя ?? имя(id),
      царство: r.царство,
      от: от.get(id)!,
      лет: r.n,
      ...(r.месяцев && { месяцев: r.месяцев }),
      стихЛет: r.стих,
      стихВоцарения: воцарение(id)?.стих,
      по: по.get(id),
    }))
    .sort((a, b) => a.от - b.от);
  const царь = new Map(цари.map((x) => [x.id, x]));
  const последний = (k: Царь) => k.от + Math.max(1, k.лет) - 1;
  const статус = (d: number): Статус => (d === 0 ? 'выполнен' : Math.abs(d) === 1 ? 'до года' : 'напряжение');
  const проверки: Проверка[] = [];
  // 1. все синхронизмы глав 15–18 (и те, что поставили царя — выполнены по построению)
  for (const s of синх) {
    if (!главы(s.стих)) continue;
    const a = царь.get(s.кто);
    const b = царь.get(s.с);
    if (!a || !b) continue;
    const вышло = a.от + s.свой - 1 - b.от + 1;
    const d = вышло - s.год;
    const имяA = a.имя.split(',')[0];
    const имяB = b.имя.split(',')[0];
    const что = s.свой === 1 ? `${имяA} воцарился` : `${s.свой}-й год; ${a.царство}: ${имяA}`;
    проверки.push({
      текст: d === 0 ? `${что}: ${s.год}-й год; ${b.царство}: ${имяB}` : `${что}: по стиху — ${s.год}-й год; ${b.царство}: ${имяB}; по этому счёту выходит ${вышло}-й`,
      стихи: [s.стих, ...(a.по && a.по.стих !== s.стих ? [a.по.стих] : [])],
      статус: статус(d),
      разница: d,
    });
    // 2. номер года синхронизма не больше числа лет того царя
    if (b.лет && s.год > b.лет)
      проверки.push({ текст: `${s.год}-й год; ${b.царство}: ${имяB} — а лет царствования по стиху ${b.лет}`, стихи: [s.стих, b.стихЛет ?? ''], статус: 'напряжение', разница: s.год - b.лет });
  }
  // 3. преемство в царстве: следующий воцаряется в последний год прежнего или в следующий за ним
  for (const ц of ['Иудея', 'Израиль'] as Царство[]) {
    const xs = цари.filter((k) => k.царство === ц);
    for (let i = 1; i < xs.length; i++) {
      const p = xs[i - 1];
      const n = xs[i];
      const d = n.от - последний(p) - 1;
      if (d === 0 || d === -1) continue;
      const до = d === 1 || d === -2;
      проверки.push({
        текст: d > 0 ? `${ц}: между концом царствования (${p.имя.split(',')[0]}) и воцарением (${n.имя.split(',')[0]}) по этому счёту ${d} г.` : `${ц}: царствования (${p.имя.split(',')[0]}; ${n.имя.split(',')[0]}) по этому счёту идут вместе ${-d} г.`,
        стихи: [p.стихЛет ?? '', n.стихВоцарения ?? ''].filter(Boolean),
        статус: до ? 'до года' : 'напряжение',
        разница: d,
      });
    }
  }
  const события: Событие[] = [];
  for (const k of цари) if (k.стихВоцарения && главы(k.стихВоцарения)) события.push({ год: k.от, текст: `воцарился ${k.имя.split(',')[0]}`, стих: k.стихВоцарения, царь: k.id });
  for (const x of НАРОДЫ) {
    const k = царь.get(x.царь);
    if (k) события.push({ год: k.от + x.год - 1, текст: x.текст, стих: x.стих });
  }
  return { цари, проверки, события: события.sort((a, b) => a.год - b.год), синхронизмы: синх };
}

/** Номер года царя на оси (`null` — царь в этот год не царствует по числам стиха). */
export function годЦаря(k: Царь, год: number): number | null {
  const n = год - k.от + 1;
  if (n < 1) return null;
  if (k.лет === 0) return n === 1 ? 1 : null;
  return n <= k.лет ? n : null;
}
