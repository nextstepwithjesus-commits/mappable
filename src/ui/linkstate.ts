/**
 * Состояние выбранной связи (этап 11, решение 83). Ключ связи — src/engine/linkkey.ts.
 *
 * selectedLink — связь, которую выбрал читатель: щелчком или касанием линии на небе, строкой «Родство» карточки у звезды
 * или адресом «~c». Выбор связи не меняет выбранное лицо. Небо рисует её отличительным цветом, у концов — кольца,
 * рядом — карточка связи; Escape, «×» или щелчок по пустому небу снимают выбор.
 *
 * previewLinks — связи, которые подсвечены без выбора: наведение или фокус клавиатуры на строке «Родство» карточки
 * у звезды («Сыновья» подсвечивают линии ко всем сыновьям), наведение на линию.
 *
 * linkGhosts — концы выбранной связи, которых нет звездой на экране: вне показа, свёрнуты или за краем (этап 13,
 * решение 93; контракт 2).
 */
import { signal } from '@preact/signals';
import type { LinkKey } from '../engine/linkkey.ts';

export const selectedLink = signal<LinkKey | null>(null);
export const previewLinks = signal<readonly LinkKey[] | null>(null);

/**
 * Где на экране стоит выбранная связь (координаты неба в px от левого верхнего угла холста): точка щелчка по линии или,
 * если связь выбрана строкой «Родство» или адресом, середина её пути в кадре. Ставит и обновляет небо (при сдвиге и
 * масштабе); null — связь вне кадра. По ней карточка связи встаёт рядом с линией.
 */
export const linkAnchor = signal<{ x: number; y: number } | null>(null);

// ---------- концы выбора, не нарисованные на небе (этап 13, решение 93, К2–К3; контракт 2) ----------

/**
 * Почему конец выбранной связи не стоит на экране звездой:
 *  show   — лица нет в нынешнем показе («вне показа»): небо ставит на его место призрак — пунктирное кольцо в его год;
 *  folded — лицо спрятано свёрткой («скрыт на небе»: «+N» у ромба, скрытое созвездие; словарь 109 — на небе «скрыть»):
 *           тоже призрак;
 *  edge   — лицо на небе, но за краем окна («за краем»): указатель у кромки «‹ Иаков, отец».
 */
export type GhostWhy = 'show' | 'folded' | 'edge';

/** Слова причины — для строк карточки связи, подписи призрака и диктора. */
export const GHOST_WORD: Readonly<Record<GhostWhy, string>> = { show: 'вне показа', folded: 'скрыт на небе', edge: 'за краем' };

/** Конец выбранной связи, которого нет звездой на экране. */
export interface LinkGhost {
  /** лицо-конец */
  id: string;
  /** его роль в связи — та же, что у кольца конца (linkRoles, src/ui/linkwords.ts): «отец», «дочь», «сестра»; '' — роли нет */
  role: string;
  why: GhostWhy;
  /** запись ключа выбранной связи (linkKeyString), к которой относится конец */
  ks: string;
}

/**
 * Концы выбранной связи (selectedLink), которых нет звездой на экране, — в порядке концов связи (старшая сторона первой).
 * Ставит небо в каждом кадре (src/render/marks.ts, drawSelectedLink); пусто — связь не выбрана или оба конца видны.
 * Карточка связи показывает по ним строку «Илий, отец — вне показа — показать Илия» (T6: showGuest, src/ui/show.ts).
 */
export const linkGhosts = signal<readonly LinkGhost[]>([]);

const ghostsKey = (list: readonly LinkGhost[]) => list.map((g) => `${g.ks}|${g.id}|${g.role}|${g.why}`).join(';');

/** Поставить концы-призраки кадра: сигнал меняется, только если список стал другим (небо зовёт это в каждом кадре). */
export function putLinkGhosts(list: readonly LinkGhost[]) {
  if (ghostsKey(list) === ghostsKey(linkGhosts.peek())) return;
  linkGhosts.value = list;
}
