function Caps({ keys }: { keys: string[] }) {
  const out: ComponentChildren[] = [];
  keys.forEach((k, i) => {
    if (i) out.push(' ');
    out.push(<kbd>{k}</kbd>);
  });
  return <>{out}</>;
}

/** Клавиши строки: надписи английской раскладки, под ними — русской, если они другие; mod — клавиша, которую держат. */
function KeyCell({ keys, mod }: { keys: Key[]; mod?: string }) {
  const ru = keys.some((k) => k.ru);
  return (
    <>
      {/* строка клавиш не переносится: колонка таблицы — по самой длинной строке */}
      <span class="nobr">
        {mod ? (
          <>
            <kbd>{mod}</kbd>{'\u00a0'}+{' '}
          </>
        ) : null}
        <Caps keys={keys.map((k) => k.en)} />
      </span>
      {ru ? (
        <>
          <br />
          <span class="nobr">
            <span class="muted">рус.</span>{'\u00a0'}
            <Caps keys={keys.map((k) => k.ru ?? k.en)} />
          </span>
        </>
      ) : null}
    </>
  );
}

/** Переключатель «Клавиши-буквы: вкл. | выкл.» (решение 48; WCAG 2.1.4). */
const LETTER_OPTIONS = [
  { value: 'on', label: 'вкл.' },
  { value: 'off', label: 'выкл.' },
] as const;

/**
 * Строка, чьи клавиши все выключает «Клавиши-буквы: выкл.» (src/ui/keys.ts, isCharKey): одиночные буквы, цифры и знаки
 * без Shift, кроме «/», «?», «+» и «−». Стрелки — не знаки; у строки «0, Home» Home работает всегда.
 */
export const isLetterRow = (r: KeyRow) => !r.mod && r.keys.every((q) => [...q.en].length === 1 && !'/?+−←→↑↓'.includes(q.en));

/** Таблица клавиш: клавиши обеих раскладок и действие. */
export function KeysTable() {
  const on = letterKeys.value;
  return (
    <>
      <div class="letter-keys">
        <span class="k" aria-hidden="true">
          Клавиши-буквы:
        </span>
        <Segmented label="Клавиши-буквы" options={LETTER_OPTIONS} value={on ? 'on' : 'off'} onChange={(v) => (letterKeys.value = v === 'on')} />
      </div>
      <p class="muted">
        {typo(
          on
            ? 'Одиночные буквы и знаки ниже (F, J, D, «[», «0» и другие) можно выключить, если они мешают, например при вводе голосом. Стрелки, Enter, Escape, «/», «?», «+» и «−» работают всегда.'
            : 'Одиночные буквы и знаки выключены: их строки в таблице помечены «выключено». Стрелки, Enter, Escape, «/», «?», «+» и «−» работают.',
        )}
      </p>
      <p class="muted">{typo('Клавиши привязаны к месту на клавиатуре: на русской раскладке нажимается та же клавиша, её надпись — после «рус.».')}</p>
      <table class="keys">
        <thead>
          <tr>
            <th scope="col">Клавиши</th>
            <th scope="col">Действие</th>
          </tr>
        </thead>
        <tbody>
          {KEY_ROWS.map((r) => {
            const off = !on && isLetterRow(r);
            return (
              <tr key={r.what} class={off ? 'off' : undefined}>
                <td>
                  <KeyCell keys={r.keys} mod={r.mod} />
                </td>
                <td>
                  {typo(r.what)}
                  {off ? <span class="muted"> (выключено)</span> : null}
                </td>
              </tr>
            );
          })}
        </tbody>
      </table>
      <h3>Мышь, тачпад, касание</h3>
      <table class="keys">
        <tbody>
          {POINTER_ROWS.map((r) => (
            <tr key={r.how}>
              <td class="how">{typo(r.how)}</td>
              <td>{typo(r.what)}</td>
            </tr>
          ))}
        </tbody>
      </table>
    </>
  );
}
