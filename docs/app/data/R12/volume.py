"""R12: объём каталога историй — проба и экстраполяция по группам книг (стихи считаются по synodal.tsv)."""
import sys, collections
REPO = sys.argv[1]
V = collections.defaultdict(int)  # (книга, глава) -> стихов
for line in open(f'{REPO}/tools/bible/synodal.tsv', encoding='utf-8'):
    b, c, v, _ = line.split('\t', 3); V[(b, int(c))] += 1
def n(book, chs): return sum(V[(book, c)] for c in chs)
R = lambda a, z: range(a, z + 1)
# Повествование ВЗ (группа А): главы с рассказом
A = {
 'Быт': R(1, 50), 'Исх': list(R(1, 20)) + [24] + list(R(32, 34)), 'Чис': list(R(9, 14)) + [16, 17] + list(R(20, 25)) + [31, 32],
 'Втор': R(31, 34), 'Нав': list(R(1, 12)) + list(R(22, 24)), 'Суд': R(1, 21), 'Руф': R(1, 4),
 '1Цар': R(1, 31), '2Цар': R(1, 24), '3Цар': R(1, 22), '4Цар': R(1, 25),
 'Езд': [1] + list(R(3, 10)), 'Неем': list(R(1, 2)) + list(R(4, 6)) + list(R(8, 9)) + [13], 'Есф': R(1, 10),
 'Ион': R(1, 4), 'Дан': R(1, 6),
}
Apar = {'1Пар': R(10, 29), '2Пар': R(1, 36)}
a = sum(n(b, c) for b, c in A.items()); ap = sum(n(b, c) for b, c in Apar.items())
print('А, стихов повествования ВЗ:', a, '; Пар 10–36:', ap)
# Проба
probe = {'Руф 1–4': (n('Руф', R(1, 4)), 5, 9), '1Цар 16–31': (n('1Цар', R(16, 31)), 27, 44),
         'Мк 1–3': (n('Мк', R(1, 3)), 20, 20), 'Деян 1–5': (n('Деян', R(1, 5)), 10, 18)}
tv = ts = tp = 0
for k, (v, s, p) in probe.items():
    tv += v; ts += s; tp += p
    print(f'{k}: стихов {v}, историй {s} (1 на {v/s:.1f}), частей {p} (1 на {v/p:.1f})')
print(f'всего проба: стихов {tv}, историй {ts}, частей {tp}')
# Экстраполяция: (мин, макс) историй
dens = (14, 20)  # стихов на историю в повествовании ВЗ (проба: Руфь 17, 1Цар 16)
A_lo, A_hi = a / dens[1], a / dens[0]
P_lo, P_hi = ap * 0.4 / dens[1], ap * 0.6 / dens[0]   # своё у Пар — 40–60 % повествования
gospel = (250, 350); acts = (n('Деян', R(1, 28)) / 18, n('Деян', R(1, 28)) / 14)
groups = [('А. Повествование ВЗ', A_lo, A_hi), ('А′. Своё у 1–2 Пар', P_lo, P_hi), ('Б. Закон, перечни, речи Моисея', 40, 70),
          ('В. Иов (прочие поэтические — 0)', 5, 8), ('Г. Пророки (видения, знамения, рассказы)', 70, 95),
          ('Д. Евангелия (без повторов)', *gospel), ('Е. Деяния', *acts), ('Ж. Послания', 5, 10), ('З. Откровение', 15, 25)]
lo = hi = 0
for name, l, h in groups:
    lo += l; hi += h; print(f'{name}: {l:.0f}–{h:.0f}')
print(f'ИТОГО историй: {lo:.0f}–{hi:.0f}; частей (×{tp/ts:.2f} по пробе): {lo*tp/ts:.0f}–{hi*tp/ts:.0f}')
