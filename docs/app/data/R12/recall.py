"""Проба R12: находит ли OpenBible (TSK) известные параллели и упоминания (в обе стороны), с каким числом голосов."""
import json, sys, collections, re
REPO, XREF = sys.argv[1], sys.argv[2]
OSIS = ['Gen','Exod','Lev','Num','Deut','Josh','Judg','Ruth','1Sam','2Sam','1Kgs','2Kgs','1Chr','2Chr','Ezra','Neh','Esth','Job','Ps','Prov','Eccl','Song','Isa','Jer','Lam','Ezek','Dan','Hos','Joel','Amos','Obad','Jonah','Mic','Nah','Hab','Zeph','Hag','Zech','Mal','Matt','Mark','Luke','John','Acts','Jas','1Pet','2Pet','1John','2John','3John','Jude','Rom','1Cor','2Cor','Gal','Eph','Phil','Col','1Thess','2Thess','1Tim','2Tim','Titus','Phlm','Heb','Rev']
order = []
for line in open(f'{REPO}/tools/bible/synodal.tsv', encoding='utf-8'):
    b = line.split('\t', 1)[0]
    if not order or order[-1] != b: order.append(b)
S2O = dict(zip(order, OSIS))
vm = json.load(open(f'{REPO}/base/versification/synodal-kjv.json'))['map']
def kset(ref):
    m = re.match(r'(\S+) (\d+):(\d+)(?:-(\d+))?$', ref)
    b, c, v1, v2 = m[1], int(m[2]), int(m[3]), int(m[4] or m[3])
    out = set()
    for v in range(v1, v2 + 1):
        out.update(vm.get(f'{b} {c}:{v}', [f'{S2O[b]}.{c}.{v}']))
    return out
def expand(t):
    a, _, z = t.partition('-')
    if not z: return {a}
    ab, ac, av = a.split('.'); zb, zc, zv = z.split('.')
    if ac != zc: return {a, z}
    return {f'{ab}.{ac}.{v}' for v in range(int(av), int(zv) + 1)}
edges = collections.defaultdict(int)
for line in open(XREF, encoding='utf-8'):
    if line.startswith('From'): continue
    a, b, n = line.rstrip('\n').split('\t')
    for t in expand(b):
        edges[(a, t)] = max(edges[(a, t)], int(n)); edges[(t, a)] = max(edges[(t, a)], int(n))
