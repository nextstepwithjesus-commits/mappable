found = tot = 0
for name, ref, gold in GOLD:
    A = kset(ref)
    for g, kind in gold:
        B = kset(g); best = max((edges.get((a, b), 0) for a in A for b in B), default=0)
        tot += 1; found += best > 0
        print(f'{name:24} {ref:15} → {g:14} {kind:22} голосов: {best if best else "НЕТ"}')
print(f'найдено {found} из {tot}')
