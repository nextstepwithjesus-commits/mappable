 ('Зифеи', '1Цар 23:19-28', [('Пс 53:2', 'упоминание')]),
 ('Аэндор', '1Цар 28:3-25', [('1Пар 10:13-14', 'упоминание')]),
 ('Смерть Саула', '1Цар 31:1-13', [('1Пар 10:1-12', 'параллель'), ('2Цар 1:1-10', 'другой рассказ'), ('2Цар 21:12', 'упоминание')]),
 ('Крещение', 'Мк 1:9-11', [('Мф 3:13-17', 'параллель'), ('Лк 3:21-22', 'параллель'), ('Ин 1:32-34', 'упоминание')]),
