# Рецензия доступности на 03: контраст по токенам R8 § 4.2 (формула WCAG 2.x).
# Запуск из корня: python3 -I "docs/app/data/03-доступность/контраст.py"
# Токены — docs/app/research/R8-design.md, § 4.2; другой палитры у 03 пока нет.

T = {
    'светлая': dict(фон='#F4F6F9', лист='#FFFFFF', подложка='#E8ECF1', чернила='#18202C', чернила2='#4A5463',
                    линия='#6E7888', сетка='#C9D0DA', выбор='#FFD43B', область='#FFF1BF', мф='#17599A', лк='#CC5596'),
    'тёмная': dict(фон='#161D27', лист='#1E2733', подложка='#2A3442', чернила='#E8ECF1', чернила2='#A9B3C1',
                   линия='#7A8596', сетка='#3A4555', выбор='#F0D04A', область='#4A4426', мф='#9AD1F7', лк='#E4579C'),
}

def rgb(h): return [int(h[i:i + 2], 16) / 255 for i in (1, 3, 5)]
def lum(c):
    c = [x / 12.92 if x <= 0.03928 else ((x + 0.055) / 1.055) ** 2.4 for x in c]
    return 0.2126 * c[0] + 0.7152 * c[1] + 0.0722 * c[2]
def cr(a, b):
    la, lb = lum(rgb(a) if isinstance(a, str) else a), lum(rgb(b) if isinstance(b, str) else b)
    return (max(la, lb) + 0.05) / (min(la, lb) + 0.05)
def mix(fg, bg, a):
    f, b = rgb(fg), rgb(bg)
    return [a * x + (1 - a) * y for x, y in zip(f, b)]

for th, t in T.items():
    print(f'== {th} тема')
    # 1. Одно кольцо фокуса цвета «чернила» (03 § 7: «не меньше 3 : 1 к фону») рядом с тем, что бывает под узлом
    for bg in ('фон', 'лист', 'подложка', 'область', 'выбор'):
        print(f'   кольцо «чернила» к «{bg}»: {cr(t["чернила"], t[bg]):.2f}')
    # 2. Двойное кольцо R8 (чернила внутри, лист снаружи): хватает ли одного из колец 3 : 1 к любому соседу
    for bg in ('фон', 'подложка', 'область', 'выбор', 'мф', 'лк'):
        a, b = cr(t['чернила'], t[bg]), cr(t['лист'], t[bg])
        print(f'   двойное кольцо к «{bg}»: чернила {a:.2f}, лист {b:.2f} -> {"да" if max(a, b) >= 3 else "НЕТ"}')
    # 3. Линии внутри выбранной области (заливка R8)
    for fg in ('линия', 'мф', 'лк', 'чернила2'):
        print(f'   «{fg}» на заливке выбранной области: {cr(t[fg], t["область"]):.2f}')
    # 4. Заливка выбранной области к фону и листу: видна ли сама заливка
    print(f'   заливка области к фону {cr(t["область"], t["фон"]):.2f}, к листу {cr(t["область"], t["лист"]):.2f}')
    # 5. «Приглушить остальное» (03 § 3.5) непрозрачностью: наименьшая непрозрачность для норм
    for fg, need in (('линия', 3.0), ('чернила2', 4.5), ('чернила', 4.5)):
        for bg in ('фон', 'подложка'):
            amin = next((a / 100 for a in range(10, 101) if cr(mix(t[fg], t[bg], a / 100), t[bg]) >= need), None)
            print(f'   приглушённое «{fg}» на «{bg}» держит {need} : 1 только при непрозрачности не ниже {amin}')
    for a in (0.25, 0.4, 0.6):
        print(f'   при {int(a*100)} %: «линия» на фоне {cr(mix(t["линия"], t["фон"], a), t["фон"]):.2f};'
              f' «чернила-2» на фоне {cr(mix(t["чернила2"], t["фон"], a), t["фон"]):.2f};'
              f' «чернила» на фоне {cr(mix(t["чернила"], t["фон"], a), t["фон"]):.2f}')
    # 6. «Сетка» (тени свёрнутых ветвей, предложение арт-директора) — к фону
    print(f'   «сетка» к фону {cr(t["сетка"], t["фон"]):.2f}')
