import re, sys, collections
ROOT = '/home/user/mappable/'
TEXT = {}
for line in open(ROOT + 'tools/bible/synodal.tsv', encoding='utf-8'):
    b, c, v, t = line.rstrip('\n').split('\t', 3)
    TEXT[(b, int(c), int(v))] = t

def verses(ref):
    out = []
    for seg in ref.split(';'):
        seg = seg.strip()
        m = re.match(r'^(\S+) (\d+):(\d+)(?:-(?:(\d+):)?(\d+))?$', seg)
        b, c1, v1 = m[1], int(m[2]), int(m[3])
        c2 = int(m[4]) if m[4] else c1
        v2 = int(m[5]) if m[5] else v1
        c, v = c1, v1
        while (c, v) <= (c2, v2):
            if (b, c, v) in TEXT:
                out.append((b, c, v)); v += 1
            else:
                c, v = c + 1, 1
                if c > 200: break
    return out

def words(keys):
    return sum(len(re.findall(r'[А-Яа-яЁё]+', TEXT[k])) for k in keys)

