def verses(ref):
    """«Быт 6:9-9:17», «1Цар 28:1-2», «Мк 2:1-12» → список стихов по порядку."""
    m = re.match(r'^(\S+) (\d+):(\d+)(?:-(?:(\d+):)?(\d+))?$', ref)
    b, c1, v1 = m[1], int(m[2]), int(m[3])
    c2 = int(m[4]) if m[4] else c1
    v2 = int(m[5]) if m[5] else v1
    out, c, v = [], c1, v1
    while (c, v) <= (c2, v2):
        if (b, c, v) in TEXT:
            out.append((b, c, v))
            v += 1
        else:
            c, v = c + 1, 1
            if c > 200:
                break
    return out


def outside(key):
    """Текст стиха без слов в скобках (любого вида — для проверки «вне скобок»)."""
    t = TEXT[key]
    t = re.sub(r'\[[^\]]*\]', ' ', t)
    t = re.sub(r'\([^)]*\)', ' ', t)
    return ' '.join(t.lower().replace('ё', 'е').split())


def has(refs, word):
    w = word.lower().replace('ё', 'е')
    return [f'{b} {c}:{v}' for r in refs for (b, c, v) in verses(r) if w in outside((b, c, v))]


def nv(refs):
    return sum(len(verses(r)) for r in refs)


