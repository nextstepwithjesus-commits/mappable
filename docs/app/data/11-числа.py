# ЧТО ЭТО ПРОВЕРЯЕТ (ред. 2.1, библ. Н-1). Скрипт НЕ выводит границы из текста. Вид начала каждого отрезка
# („дело“, „заглавие“, „шаг“, „круг“, „следствие“ и т. д.) — разметка составителя, вписанная сюда рукой.
# Скрипт делает три вещи: (1) проверяет, что каждое слово-опора стоит в своём стихе вне скобок;
# (2) выводит исход отрезка (история, часть, свод закона) из пометки по ПОРЯДКУ правил § 2.2 — одинаково для всех
# примеров, без исключений по месту; (3) для первых пяти примеров считает старое правило „два признака из четырёх“.
# Верна ли сама пометка (есть ли здесь новое дело) — решает человек; это проверяет проба П7 двумя разметчиками.
#
# Пометки (по порядку правил § 2.2):
#   'заглавие'     — правило 1: заглавие самого текста („Вот житие Ноя“) → новая история;
#   'внутри дела'  — правило 2: время сцены текст ставит внутрь ещё не решённого дела → часть;
#   'шаг'          — правило 2: шаг дела, двигающий его к развязке → часть;
#   'круг'         — правило 3: шаг-круг — своя завязка и своя развязка, после которой дело стоит там же → история
#                    (общее дело становится повествованием);
#   'видение'      — правило 4: новое видение по словам показа или новой дате → история (ряд — повествование);
#   'дело'         — правило 5: после развязки начинается новое дело → история, даже если текст связывает её словами;
#   'следствие'    — правило 6: после развязки нового дела нет, текст связывает сцену словами → часть;
#   (правило 7 — разрыв и вставка — видно по стихам отрезков: „шаг“ после чужой истории — второй отрезок)
#   'свод'         — правило 8: свод законов внутри дела (> 500 слов, без действия) → класс „закон“, у истории разрыв;
#   'речь'         — § 2.2 „Речь, закон и пророчество“: речь без рассказанной обстановки → вне историй.
STORY_MARKS = {'заглавие', 'круг', 'видение', 'дело'}
PART_MARKS = {'внутри дела', 'шаг', 'следствие'}


def outcome(i, mark):
    if i == 0:
        return 'начало'
    if mark in STORY_MARKS:
        return f'история ({mark})'
    if mark in PART_MARKS:
        return f'часть ({mark})'
    if mark == 'свод':
        return 'класс „закон“ (разрыв истории)'
    if mark == 'речь':
        return 'класс „пророчество“ (вне историй)'
    raise ValueError(mark)


