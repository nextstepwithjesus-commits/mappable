"""Рецензия доступности на 08, редакция 3: числа, которых нет в 08-числа.py.

Запуск из корня: python3 -I docs/app/data/08-доступность/ред3.py [--fonts ПАПКА]
Части:
  1 — выбор строки списка (08 § 7.27: «плашка „выбор“ под именем», кольца нет) — контраст указателя состояния (1.4.11);
      категориальные цвета в тёмной теме без контура; переключатель слоя: нажато / не нажато;
  2 — адрес-кнопка в строке списка: высота цели против 24 px (2.5.8) и против своей нормы касания 44 (08 § 3.5);
  3 — указатель лиц (2 689 записей base/actors): остановки Tab и смахивания VoiceOver/TalkBack;
  4 — прилипающая шапка таблицы (08 § 7.13, § 7.27) и закреплённая шапка: сколько окна занято при 100 %, 200 %, 400 %;
  5 — строка лица на телефоне 320 с адресом и «Подробнее» в той же строке: сколько места остаётся имени.
Файлы проекта скрипт не меняет.
"""
import glob
import json
import os
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', '..', '..'))
FONTS = os.path.join(ROOT, 'inputs', 'fonts')
if '--fonts' in sys.argv:
    FONTS = sys.argv[sys.argv.index('--fonts') + 1]

T = {  # 08 § 3.2.1, ред. 3
    'фон': ('#F4F6F9', '#161D27'), 'лист': ('#FFFFFF', '#1E2733'), 'подложка': ('#E8ECF1', '#2A3442'),
    'чернила': ('#18202C', '#E8ECF1'), 'чернила-2': ('#4A5463', '#A9B3C1'), 'линия': ('#6E7888', '#7A8596'),
    'выбор': ('#FFD43B', '#F0D04A'), 'сетка': ('#C9D0DA', '#3A4555'),
    'кат-1': ('#D55E00', '#D55E00'), 'кат-2': ('#009E73', '#009E73'),
    'кат-3': ('#E69F00', '#E69F00'), 'кат-4': ('#56B4E9', '#56B4E9'),
}
TH = ('светлая', 'тёмная')


def lum(h):
    h = h.lstrip('#')
    c = [int(h[i:i + 2], 16) / 255 for i in (0, 2, 4)]
    c = [x / 12.92 if x <= 0.04045 else ((x + 0.055) / 1.055) ** 2.4 for x in c]
    return 0.2126 * c[0] + 0.7152 * c[1] + 0.0722 * c[2]


def cr(a, b):
    la, lb = lum(a), lum(b)
    return (max(la, lb) + 0.05) / (min(la, lb) + 0.05)


def f2(x):
    return f'{x:.2f}'.replace('.', ',')


def head(s):
    print('\n' + '=' * 78 + '\n' + s + '\n' + '=' * 78)


# ---------------------------------------------------------------- 1
head('1. Указатели состояния без кольца: выбор строки, категориальные в тёмной, переключатель слоя (1.4.11)')
print('Выбор строки списка — только жёлтая плашка под именем (08 § 7.27 «Состояния», § 7.13): плашка к соседнему полю')
for bg in ('лист', 'фон', 'подложка'):
    v = [cr(T['выбор'][i], T[bg][i]) for i in (0, 1)]
    print(f'  выбор / {bg:9s}  светлая {f2(v[0]):>6}  тёмная {f2(v[1]):>6}  ' +
          ' '.join('✗' if x < 3 else '✓' for x in v))
print('  (подложка — строка под указателем и полоса через одну во втором слое)')
print('\nКатегориальные в тёмной теме: контура «чернила» нет (08 § 3.2.1 — контур только в светлой)')
for k in ('кат-1', 'кат-2', 'кат-3', 'кат-4'):
    v = [cr(T[k][1], T[bg][1]) for bg in ('лист', 'фон', 'подложка')]
    print(f'  {k}: к листу {f2(v[0])}, к фону {f2(v[1])}, к подложке {f2(v[2])}  ' +
          ('✓' if min(v) >= 3 else '✗ ниже 3 : 1'))
print('\nПереключатель слоя (08 § 7.9): не нажата — лист и рамка «линия»; нажата — «подложка», рамка «чернила», 600')
for i in (0, 1):
    print(f'  {TH[i]}: заливка нажатой к ненажатой {f2(cr(T["подложка"][i], T["лист"][i]))}; '
          f'рамка «чернила» к рамке «линия» {f2(cr(T["чернила"][i], T["линия"][i]))}; '
          f'рамка «линия» к листу {f2(cr(T["линия"][i], T["лист"][i]))}')
print('  Различие «нажато / не нажато» держится на рамке 1 px другого тона и насыщенности 600; заливка — 1,2 : 1.')

# ---------------------------------------------------------------- 2
head('2. Адрес-кнопка и «Подробнее» в строке списка: высота цели (2.5.8 — 24; норма 08 на касании — 44)')
rows = [
    ('ноутбук, один ярус, обычная', 36, 18, 'pointer: fine', 24),
    ('ноутбук, плотная', 28, 18, 'pointer: fine', 24),
    ('телефон, два яруса (адрес во втором ярусе 13/16)', 44, 16, 'pointer: coarse', 44),
]
for name, row, line, ptr, norm in rows:
    # самое большее, что адрес может получить без роста строки: в один ярус — вся высота строки;
    # в два яруса — второй ярус плюс нижнее поле (4), без залезания на название
    room = row if 'один' in name or 'плотная' in name else line + 4
    print(f'  {name}: строка {row}, строка адреса {line} px; адрес-кнопке доступно до {room} px; '
          f'норма {ptr} — {norm}: {"✓ можно, если задать" if room >= norm else "✗ не помещается"}; '
          f'2.5.8 (24): {"✓ можно, если задать" if room >= 24 else "✗"}')
print('  Исключение 2.5.8 «в строке текста» относится к цели внутри предложения; ячейка адреса строки списка')
print('  не предложение, и её высоту задаёт сам компонент. Исключение по промежутку не работает: круг 24 px')
print('  вокруг адреса задевает растянутую на всю строку ссылку названия (`::after`).')

# ---------------------------------------------------------------- 3
head('3. Указатель лиц: 2 689 строк (base/actors/*.json, поле items)')
n = 0
for f in sorted(glob.glob(os.path.join(ROOT, 'base', 'actors', '*.json'))):
    n += len(json.load(open(f, encoding='utf-8'))['items'])
print(f'  записей: {n}')
for label, k in (('имя-ссылка', 1), ('имя + адрес-кнопка', 2), ('имя + адрес + „Подробнее“', 3)):
    print(f'  {label}: остановок Tab ' + f'{n * k:,}'.replace(',', ' '))
for label, k in (('VoiceOver iOS / TalkBack: имя, роль, адрес — 3 смахивания', 3),
                 ('то же + „Подробнее“ — 4', 4)):
    t = n * k
    print(f'  {label}: ' + f'{t:,}'.replace(',', ' ') + f' смахиваний; по 1 с — {t / 60:.0f} мин')
print('  Ротор «Заголовки» без деления на буквы: 0 опор внутри списка; с делением по первой букве — около 30.')

# ---------------------------------------------------------------- 4
head('4. Прилипающая шапка таблицы + закреплённая шапка: доля высоты окна')
CASES = [('1280 × 720, 100 %', 720, 1, False), ('1280 × 720, 200 % (640 × 360)', 360, 2, False),
         ('1280 × 1024 (окно ≈ 900), 400 % (320 × 225)', 225, 4, True), ('телефон 360 × 560', 560, 1, False),
         ('телефон лёжа 640 × 360', 360, 1, False)]
PHONE = ('телефон 360 × 560',)
for name, h, z, narrow in CASES:
    header = 0 if h <= 480 else (56 if name in PHONE else 64)  # 08 § 3.4, § 7.1
    thead_lines = 2 if narrow else 1          # подписи столбцов 15/20 переносятся при 320 px
    thead = 16 + 20 * thead_lines
    tot = header + thead
    print(f'  {name}: шапка {header} + шапка таблицы {thead} = {tot} px — {tot / h * 100:.0f} % окна; '
          f'строк 36 px под ними целиком: {max(0, (h - tot) // 36)}')
print('  scroll-padding-top = высоте шапки (08 § 3.4) не учитывает шапку таблицы: при Shift + Tab вверх')
print('  строка 36 px встаёт под шапку таблицы 36 px и закрыта целиком — нарушение 2.4.11.')

# ---------------------------------------------------------------- 5
head('5. Строка лица на телефоне 320: место имени, если в той же строке адрес и „Подробнее“')
try:
    sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
    from fontTools.ttLib import TTFont
    from fontTools.varLib import instancer

    def face(path, loc):
        f = TTFont(path)
        inst = instancer.instantiateVariableFont(f, loc)
        return inst.getBestCmap(), inst['hmtx'].metrics, inst['head'].unitsPerEm

    def width(s, fc, px):
        cmap, hm, upm = fc
        return sum(hm[cmap.get(ord(ch), cmap.get(0x20))][0] for ch in s) * px / upm

    golos600 = face(os.path.join(FONTS, 'GolosText[wght].ttf'), {'wght': 600})
    golos450 = face(os.path.join(FONTS, 'GolosText[wght].ttf'), {'wght': 450})
    lit600 = face(os.path.join(FONTS, 'Literata[opsz,wght].ttf'), {'opsz': 16, 'wght': 600})
    more = width('Подробнее', golos600, 15) + 16 + 12  # значок 12 и поля 8 + 8
    more = max(more, 44)
    addr = width('1 Пар 3:5', golos450, 13) + 16
    col = 288 - 32  # 08 ч. 25: 288 − номер
    for scale in (1.0, 1.25):
        m = max(more * scale, 44)
        room = col - m
        names = []
        for f in sorted(glob.glob(os.path.join(ROOT, 'base', 'actors', '*.json'))):
            for it in json.load(open(f, encoding='utf-8'))['items']:
                nm = next((x.get('form', '') for x in it.get('names') or [] if x.get('type') == 'main'),
                          (it.get('names') or [{}])[0].get('form', ''))
                if nm:
                    names.append(nm)
        wide = sum(1 for nm in names if width(nm, lit600, 16 * scale) > room)
        two = sum(1 for nm in names if width(nm, lit600, 16 * scale) > 2 * room)
        print(f'  «Размер текста» {int(scale * 100)} %: „Подробнее“ {m:.0f} px; имени остаётся {room:.0f} px '
              f'(08 ч. 25 считала 256); имён длиннее одной строки — {wide}, длиннее двух — {two}; '
              f'адрес во втором ярусе ≈ {addr * scale:.0f} px')
except Exception as e:  # noqa: BLE001
    print('  шрифты не найдены или нет fontTools:', e)

print('\nГотово.')
