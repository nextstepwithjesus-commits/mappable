def rgb(h):
    h = h.lstrip('#')
    return [int(h[i:i + 2], 16) for i in (0, 2, 4)]


def hexs(c):
    return '#' + ''.join(f'{round(x):02X}' for x in c)


def lum(h):
    def lin(c):
        c /= 255
        return c / 12.92 if c <= 0.04045 else ((c + 0.055) / 1.055) ** 2.4
    r, g, b = [lin(c) for c in rgb(h)]
    return 0.2126 * r + 0.7152 * g + 0.0722 * b


def cr(a, b):
    la, lb = lum(a), lum(b)
    return (max(la, lb) + 0.05) / (min(la, lb) + 0.05)


def over(fg, bg, a):
    f, b = rgb(fg), rgb(bg)
    return hexs([a * x + (1 - a) * y for x, y in zip(f, b)])


def f2(x):
    return f'{x:.2f}'.replace('.', ',')


def need(fg, bg, norm):
    for p in range(0, 101):
        if cr(over(fg, bg, p / 100), bg) >= norm:
            return p
    return None


