"""Рецензия доступности на 08: порог основного вида «двойник» (08 § 6.1 п. 5) на настоящих окнах.

Запуск из корня: python3 -I docs/app/data/08-доступность/порог.py
Правило 08: @media (max-width: 20em), (max-height: 16em). В медиазапросах em — размер шрифта
по умолчанию в браузере (обычно 16 px), а не размер шрифта корня из CSS.
Высота окна — экран минус панели браузера и системы (оценка; числа панелей — в таблице).
Масштаб страницы делит размеры окна в CSS px; увеличение только шрифта меняет размер em.
Файлы проекта скрипт не меняет.
"""

def decide(w, h, em=16):
    we, he = w / em, h / em
    return we, he, ('двойник' if we <= 20 or he <= 16 else 'рисунок')


# (что, ширина экрана CSS px, высота окна браузера CSS px при 100 %, масштаб, размер шрифта браузера px)
CASES = [
    ('ноутбук 1280 × 1024, окно ≈ 1280 × 900, 400 %', 1280, 900, 4.0, 16),
    ('ноутбук 1280 × 1024, окно ≈ 1280 × 900, 300 %', 1280, 900, 3.0, 16),
    ('ноутбук 1366 × 768, окно ≈ 1366 × 650, 300 %', 1366, 650, 3.0, 16),
    ('ноутбук 1366 × 768, окно ≈ 1366 × 650, 200 %', 1366, 650, 2.0, 16),
    ('ноутбук 1920 × 1080, окно ≈ 1920 × 950, 400 %', 1920, 950, 4.0, 16),
    ('ноутбук 1280 × 800, 100 %, шрифт браузера 32 px (Chrome «очень крупный»)', 1280, 680, 1.0, 32),
    ('ноутбук 1280 × 800, 200 %, шрифт браузера 24 px', 1280, 680, 2.0, 24),
    ('iPhone SE (2-го поколения) 375 × 667, Safari, окно ≈ 375 × 548', 375, 548, 1.0, 16),
    ('то же, «Размер страницы» Safari 150 %', 375, 548, 1.5, 16),
    ('то же, лёжа: окно ≈ 667 × 320', 667, 320, 1.0, 16),
    ('Android 360 × 800, Chrome, окно ≈ 360 × 680', 360, 680, 1.0, 16),
    ('то же, системный размер шрифта 130 % (масштаб страницы Chrome по системе)', 360, 680, 1.3, 16),
    ('то же, лёжа: окно ≈ 800 × 300', 800, 300, 1.0, 16),
    ('планшет 768 × 1024, 200 %', 768, 950, 2.0, 16),
]
print(f'{"окно":80} {"em шир.":>8} {"em выс.":>8}  вид')
for what, w, h, z, fs in CASES:
    cw, ch = w / z, h / z
    we, he, v = decide(cw, ch, fs)
    print(f'{what:80} {we:8.1f} {he:8.1f}  {v}')
print()
print('Переход «рисунок → двойник» случается посреди работы: при увеличении 300 % → 400 % (1280 × 900),')
print('при повороте телефона и при смене размера шрифта. Куда уходит фокус с метки рисунка в эту минуту, 08 не говорит.')
