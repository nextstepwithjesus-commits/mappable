# Рецензия доступности на 11 ред. 3: цена номеров стихов-кнопок и имён-ссылок
# для программы чтения (слова, остановки Tab, смахивания VoiceOver iOS / TalkBack)
import re, os
ROOT = os.path.dirname(os.path.abspath(__file__)) + '/../../../..'
rows = [l.rstrip('\n').split('\t') for l in open(ROOT + '/tools/bible/synodal.tsv', encoding='utf-8')]
def seg(book, a, b):
    return [(int(c), int(v), t) for bk, c, v, t in rows if bk == book and a <= (int(c), int(v)) <= b]
NAME = 'Стих {v}, {book}, глава {c}. Действия'   # имя кнопки по 11 § 4.4, § 9.2
BOOK = {'Быт': 'Бытие', '1Цар': 'Первая книга Царств', 'Мк': 'Евангелие от Марка'}
def run(title, book, a, b, pat, parts):
    s = seg(book, a, b)
    words = 0; extra = 0; links = 0; swipes = 0; seen = set(); part_i = -1
    for c, v, t in s:
        pi = next(i for i, (x, y) in enumerate(parts) if x <= (c, v) <= y)
        if pi != part_i: seen = set(); part_i = pi
        t2 = re.sub(r'\[[^\]]*\]', '', t)
        words += len(t.split())
        nm = NAME.format(v=v, book=BOOK[book], c=c)
        extra += len(nm.replace(',', ' ').replace('.', ' ').split()) + 2   # + "кнопка", "свёрнуто"
        lk = 0
        for m in re.finditer(pat, t2):
            key = m.group(1)[:3]
            if key not in seen: seen.add(key); lk += 1
        links += lk
        swipes += 1 + 1 + 2 * lk          # кнопка номера + текст + (ссылка + хвост текста) на ссылку
    short = sum(2 + 1 for _ in s)        # "Стих 9" + "кнопка"
    print(f'{title}: стихов {len(s)}, слов текста {words}; имя кнопки по 11 даёт +{extra} слов (+{100*extra//words} %), '
          f'при имени «Стих N» — +{short} (+{100*short//words} %); ссылок-имён {links}; '
          f'остановок Tab в тексте (номера + имена + {len(parts)} частей) {len(s)+links+len(parts)}; '
          f'смахиваний VoiceOver iOS / TalkBack по тексту около {swipes + len(parts)}')
noy = [((6,9),(6,22)),((7,1),(7,16)),((7,17),(7,24)),((8,1),(8,14)),((8,15),(8,22)),((9,1),(9,17))]
run('Ной и потоп', 'Быт', (6,9), (9,17), r'\b(Но[йяюе]м?|Сим[ау]?|Хам[ау]?|Иафет[ау]?)\b', noy)
run('Давид и Голиаф (1 Цар 17, одна часть — пример)', '1Цар', (17,1), (17,58),
    r'\b(Давид[аеуо]?м?|Саул[аеу]?м?|Голиаф[аеу]?м?|Иессе[йяюе]м?|Елиав[аеу]?|Авенир[аеу]?)\b', [((17,1),(17,58))])
run('Пять хлебов (Мк 6:30–44)', 'Мк', (6,30), (6,44), r'\b(Иисус[аеу]?)\b', [((6,30),(6,44))])
# «Все истории»: остановки Tab по оценке 11 (приложение А § 3: 857–1 243 истории, ±20 %)
for n in (857, 1243, int(1243*1.2)):
    print(f'«Все истории», {n} строк: Список (ссылка + «Подробнее») — {2*n} остановок Tab; '
          f'Таблица 2-го слоя (+ флажок) — {3*n}; по 08 § 7.27 «длинные указатели» (одна цель) — {n}')
# Контраст подчёркивания совпадений синопсиса («линия» 2 px) — WCAG 1.4.11
def lin(c):
    c /= 255; return c/12.92 if c <= 0.04045 else ((c+0.055)/1.055)**2.4
def L(h):
    h = h.lstrip('#'); r, g, b = (int(h[i:i+2], 16) for i in (0, 2, 4)); return 0.2126*lin(r)+0.7152*lin(g)+0.0722*lin(b)
def cr(a, b):
    x, y = sorted((L(a), L(b)), reverse=True); return (x+0.05)/(y+0.05)
for th, line, sheet in (('светлая', '#6E7888', '#FFFFFF'), ('тёмная', '#7A8596', '#1E2733')):
    print(f'«линия» на «листе», {th} тема: {cr(line, sheet):.2f} : 1')
