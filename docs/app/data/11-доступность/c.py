# Контраст по токенам R8 (§ 4.2) и R13 (§ 5.3), формула WCAG 2.x
def lin(c):
    c/=255
    return c/12.92 if c<=0.04045 else ((c+0.055)/1.055)**2.4
def L(h):
    h=h.lstrip('#'); r,g,b=(int(h[i:i+2],16) for i in (0,2,4))
    return 0.2126*lin(r)+0.7152*lin(g)+0.0722*lin(b)
def cr(a,b):
    la,lb=L(a),L(b); hi,lo=max(la,lb),min(la,lb); return (hi+0.05)/(lo+0.05)
def mix(fg,bg,a):
    f=[int(fg[i:i+2],16) for i in (1,3,5)]; g=[int(bg[i:i+2],16) for i in (1,3,5)]
    return '#'+''.join('%02X'%round(a*x+(1-a)*y) for x,y in zip(f,g))
