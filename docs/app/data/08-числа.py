    """Полосы от элемента наружу: (имя, цвет)."""
    ink_name = 'на-выборе' if field == 'выбор' else 'чернила'  # на жёлтой плашке знаки и кольца — «на-выборе»
    c = lambda n: tok(ink_name if n == 'чернила' else n, th)
    el = {'залитый знак': [('знак', c('чернила'))],
          'полый знак': [('контур', c('чернила')), ('нутро', c(field))],
          'плотная кнопка': [('плашка', c('чернила'))],
          'нажатая кнопка': [('плашка', c('подложка')), ('рамка 1 px', c('чернила'))]}[kind]
    out = list(el)
    if state in ('выбран', 'выбран и фокус') and 'знак' in kind:
        out += [('зазор выбора', c(field)), ('кольцо выбора', c('чернила'))]
    if state in ('фокус', 'выбран и фокус'):
        out += [('зазор фокуса', c(field)), ('рамка фокуса', c('чернила')), ('кайма', c('лист'))]
    out += [('поле', c(field))]
    return out


