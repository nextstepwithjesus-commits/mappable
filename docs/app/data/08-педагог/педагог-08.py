"""Числа рецензии педагога на 08 «Дизайн-система».

Запуск из корня: python3 -I docs/app/data/08-педагог/педагог-08.py
Читает документы docs/app/03, 05, 07, 08, 11 и tools/bible/synodal.tsv.
Шрифтов не читает: высота строчных взята из приложения А документа 08
(Golos Text 0,530 em, Literata 0,507 em).

Части:
 1. Угловой размер высоты строчных у ступеней набора 08 на ноутбуке,
    телефоне и планшете — против нормы взрослого и детской книги.
 2. Формулы «нет сведений» простого слоя в пяти документах.
 3. Строки 08 в „лапках“: слова, которых нет в словаре простого слоя 07 § 9.3,
    и длинные строки.
 4. Где 08 и 11 мерят облик у детей (Smileyometer или выбор пары).
 5. Знаки людей: что перечисляют 08 § 5.5 и 11 § 4.3.
 6. Трудные истории: какие предметы прошли бы правило «слово в стихе вне скобок»
    и стали бы предметным знаком на обложке.
"""
import math, re, pathlib

ROOT = pathlib.Path('.')
DOCS = {
    '03': 'docs/app/03-ГЕНЕАЛОГИЯ.md',
    '05': 'docs/app/05-ГЕОГРАФИЯ.md',
    '07': 'docs/app/07-КАРТОЧКА.md',
    '08': 'docs/app/08-ДИЗАЙН-СИСТЕМА.md',
    '11': 'docs/app/11-ИСТОРИИ.md',
}
text = {k: (ROOT / v).read_text(encoding='utf-8') for k, v in DOCS.items()}


def line(t):
    print('\n' + '=' * 78 + '\n' + t + '\n' + '=' * 78)


# ---------------------------------------------------------------- 1
line('1. Высота строчных в градусах (критический размер взрослого ≈ 0,2°)')
# Физический размер CSS px: экран / ширина в CSS px. Расстояния — обычные для ребёнка.
DEV = [
    # имя, мм на CSS px, расстояние мм
    ('ноутбук 14", 1280 CSS px, 50 см', 309.9 / 1280, 500),
    ('планшет 10,2" стоя, 768 CSS px, 35 см', 155.0 / 768, 350),
    ('телефон 6,1", 360 CSS px, 30 см', 64.6 / 360, 300),
]
XH = {'Golos': 0.530, 'Literata': 0.507}
STEPS = [
    # что читает ребёнок сам; шрифт; кегль ноутбук простой; телефон простой
    ('вопрос-вход, кнопка, „Коротко“ (Golos 16)', 'Golos', 16, 16),
    ('пометка, адрес, подпись схемы (Golos 15)', 'Golos', 15, 15),
    ('имя на малой карточке, название под обложкой (Literata 20 / 18)', 'Literata', 20, 18),
    ('текст Писания (Literata 20 / 18)', 'Literata', 20, 18),
    ('h1 истории (Literata 56 / 34)', 'Literata', 56, 34),
]


def deg(px, mm_per_px, dist):
    return math.degrees(2 * math.atan(px * mm_per_px / 2 / dist))


print(f'{"ступень":66} {"ноутб.":>7} {"планш.":>7} {"тел.":>7}')
for name, font, lap, ph in STEPS:
    vals = []
    for i, (_, mm, dist) in enumerate(DEV):
        size = ph if i == 2 else lap
        vals.append(deg(size * XH[font], mm, dist))
    print(f'{name:66} ' + ' '.join(f'{v:7.2f}' for v in vals))
# Детская книга для начинающего: кегль 18–24 пт, высота строчных ≈ 0,5 кегля; 35 см
for pt in (18, 24):
    xh_mm = pt * 0.3528 * 0.5
    print(f'детская книга {pt} пт (высота строчных ≈ {xh_mm:.1f} мм) на 35 см: {deg(xh_mm, 1, 350):.2f}°')
print('Wilkins и др., 2009: Arial, высота строчных 4,2 и 5,0 мм (дети 7–9 лет);'
      f' на 35 см это {deg(4.2,1,350):.2f}° и {deg(5.0,1,350):.2f}°')
# Какой кегль Golos даёт 0,4° (середина между взрослой нормой и детской книгой)
for nm, mm, dist in DEV:
    need = 2 * dist * math.tan(math.radians(0.4) / 2) / mm / XH['Golos']
    print(f'Golos для 0,40°: {nm} — {need:.0f} px')

# ---------------------------------------------------------------- 2
line('2. Формулы «нет сведений» в строках простого слоя (в „лапках“)')
PAT = re.compile(r'„([^“]{0,120}?(?:не сказано|не называет|не говорит|не сообщается|'
                 r'не названы?|не указан[оа]?|не составлен[оа]?|не проверен[ыо]?|'
                 r'не найдено|нет сведений|не знает)[^“]{0,80})“')
KINDS = [
    ('«В Библии не сказано…»', re.compile(r'Библии не сказано|в Библии не сказано', re.I)),
    ('«Библия не говорит / не называет…»', re.compile(r'Библия (прямо )?не (говорит|называет)', re.I)),
    ('«В Писании не сообщается» / «Писание…»', re.compile(r'Писании не сообщается', re.I)),
    ('«…текст не называет» / «В тексте не названы»', re.compile(r'текст не называет|тексте не назван', re.I)),
    ('«ещё не составлено / не проверены по тексту»', re.compile(r'не составлен|не проверены по тексту', re.I)),
    ('«Мы ещё не…» / «Мы не нашли…»', re.compile(r'^Мы (ещё )?не', re.I)),
    ('«атлас …» в строке', re.compile(r'[Аа]тлас', re.I)),
]
for k in ('03', '05', '07', '08', '11'):
    found = PAT.findall(text[k])
    cnt = {n: 0 for n, _ in KINDS}
    ex = {n: '' for n, _ in KINDS}
    for s in found:
        for n, rx in KINDS:
            if rx.search(s):
                cnt[n] += 1
                ex[n] = ex[n] or s[:70]
    print(f'\n{k}: строк с формулой незнания — {len(found)}')
    for n, _ in KINDS:
        if cnt[n]:
            print(f'   {cnt[n]:3} {n:48} пример: „{ex[n]}“')

# ---------------------------------------------------------------- 3
line('3. Строки 08 в „лапках“: слова вне словаря простого слоя (07 § 9.3)')
ADULT = ['Писани', 'текст', 'атлас', 'составлен', 'проверен', 'размечен', 'сведени',
         'справочно', 'данн', 'не найдено', 'родство', 'Указатель', 'Генеалогия',
         'География', 'Связи', 'Загружаем', 'версии']
quotes = re.findall(r'„([^“]{3,200})“', text['08'])
seen = set()
rows = []
for q in quotes:
    if q in seen:
        continue
    seen.add(q)
    hits = [w for w in ADULT if w.lower() in q.lower()]
    nw = len(q.split())
    if hits or ';' in q or nw > 12:
        rows.append((q, hits, nw))
print(f'Строк в „лапках“ (без повторов): {len(seen)}; с флагом: {len(rows)}')
for q, hits, nw in rows:
    flag = ', '.join(hits) + ('; «;»' if ';' in q else '') + (f'; {nw} слов' if nw > 12 else '')
    print(f'  „{q[:90]}“ — {flag}')

# ---------------------------------------------------------------- 4
line('4. Мера облика у детей: Smileyometer или выбор пары')
for k in ('08', '11'):
    for i, l in enumerate(text[k].splitlines(), 1):
        if re.search(r'Smileyometer|This or That|выбор пары', l):
            print(f'  {k}:{i}: {l.strip()[:150]}')

# ---------------------------------------------------------------- 5
line('5. Знаки людей: 08 § 5.5 и 11 § 4.3')
m8 = re.search(r'\*\*лицо: ([^*]+)\*\*', text['08'])
m11 = re.search(r'\*\*Знак\*\* — силуэт без лица: ([^(]+)', text['11'])
print('  08:', m8.group(1) if m8 else '—')
print('  11:', m11.group(1).strip() if m11 else '—')
print('  «ребёнок» в 08 § 5.5:', 'да' if m8 and 'ребён' in m8.group(1) else 'нет')

# ---------------------------------------------------------------- 6
line('6. Трудные истории: предмет проходит правило «слово в стихе вне скобок»')
syn = {}
for l in (ROOT / 'tools/bible/synodal.tsv').read_text(encoding='utf-8').splitlines():
    b, c, v, t = l.split('\t', 3)
    syn[f'{b} {c}:{v}'] = t


def outside(t):
    return re.sub(r'\[[^\]]*\]|\([^)]*\)', ' ', t)


CASES = [
    ('Авраам приносит Исаака', 'Быт 22:10', 'нож', 'орудие'),
    ('Иаиль и Сисара', 'Суд 4:21', 'кол', 'орудие'),
    ('Левит и наложница', 'Суд 19:29', 'нож', 'орудие'),
    ('Смерть Саула', '1Цар 31:4', 'меч', 'орудие'),
    ('Давид и Голиаф', '1Цар 17:51', 'голову', 'часть тела'),
    ('Смерть Иоанна Крестителя', 'Мф 14:11', 'голову его на блюде', 'часть тела'),
    ('Елисей и дети из Вефиля', '4Цар 2:24', 'медведицы', 'животное, которое убивает'),
    ('Ной сажает виноградник', 'Быт 9:21', 'вина', 'спокойный предмет'),
    ('Давид и Голиаф', '1Цар 17:40', 'пять гладких камней', 'спокойный предмет'),
    ('Распятие', 'Ин 19:17', 'крест', 'предмет без тела'),
]
for title, ref, word, kind in CASES:
    t = syn.get(ref, '')
    ok = word.lower() in outside(t).lower()
    print(f'  {title:28} {ref:11} «{word}» — {"вне скобок" if ok else "НЕТ"}; {kind}')
print('Правило 08 § 5.7 пропустит все строки выше: ему нужен ещё фильтр трудного.')
print('\nГотово.')
