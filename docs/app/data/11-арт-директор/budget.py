"""Бюджет высоты экранов документа 11 по размерам R13 (§ 3.3, § 5.1, § 5.2).

Оценка, а не вёрстка: высоты строк — по шкале R13, цели касания — 44 px (11 § 9).
Запуск: python3 -I budget.py
"""

def total(name, parts, screen):
    y = 0
    print(f'\n{name} (экран {screen} px):')
    for label, h in parts:
        y += h
        mark = '  <-- край экрана' if y - h < screen <= y else ''
        print(f'  {label:<58} {h:>4}  итого {y:>5}{mark}')
    return y

# --- Главный экран, ноутбук 1280 × 800, раскладка «полки» (11 § 7.2, эскиз § 14.1)
cover_row = 204 + 12 + 2 * 26 + 20           # обложка 4:3 + подпись 2 строки + адрес
total('Главный экран, ноутбук', [
    ('шапка: знак, поиск, слой, «?» (одна строка, как R13)', 72),
    ('отступ', 24),
    ('строка входов (одна строка, 44 px)', 44),
    ('отступ', 32),
    ('h1 «Истории Библии» 44/48', 48),
    ('оговорка о порядке 16/24', 24),
    ('переходы «Ветхий Завет / Новый Завет» (44 px)', 44),
    ('отступ', 24),
    ('«ВЕТХИЙ ЗАВЕТ» и разделы (44 px)', 44),
    ('отступ', 16),
    ('заголовок книги «Бытие» 32/36 + «Все истории»', 36),
    ('отступ', 16),
    ('ряд обложек Бытия: 204 + подпись 2×26 + адрес 20 + 12', cover_row),
    ('отступ между книгами', 48),
    ('заголовок «Исход» + отступ', 52),
    ('ряд обложек Исхода', cover_row),
], 800)

# --- Главный экран, телефон 360 × 640
ph_row = 117 + 8 + 3 * 24 + 20             # обложка 156×117 + подпись (медиана — 3 строки) + адрес
total('Главный экран, телефон', [
    ('шапка: знак, ◐, ?, ≡', 56),
    ('поле поиска 52 + отступ 12', 64),
    ('строка входов — две строки по 44 + отступ', 100),
    ('h1 «Истории Библии» 28/32', 32),
    ('оговорка о порядке — две строки 16/24', 48),
    ('«ВЕТХИЙ ЗАВЕТ» 28 + «Бытие» 24/28 + отступы', 72),
    ('ряд из 2 обложек: 117 + подпись 3×24 + адрес 20 + 8', ph_row),
    ('отступ', 16),
    ('второй ряд', ph_row),
], 640)

# --- Страница истории, ноутбук: шапка
total('Страница «Давид побеждает Голиафа», ноутбук: шапка до текста', [
    ('шапка приложения', 72),
    ('отступ', 32),
    ('путь «Ветхий Завет › 1 Царств» 15/20 + 8', 28),
    ('h1 56/60 в 6 колонках — 2 строки (скрипт fit.py)', 120),
    ('адрес 15/20 + 16', 36),
    ('«О чём эта история» — 2 строки 20/30', 60),
    ('«Когда: …» и «Где: …» — 2 строки 16/24 + 16', 64),
    ('отступ до текста', 48),
    ('заголовок блока «Так написано в Библии» h2 26/32', 32),
], 800)

# --- Закреплённая врезка (блоки 3 и 4) — 4 колонки, около 368 px
card = 16 + 24 + 2 * 24 + 20 + 8   # поле, имя, роль в 2 строки, стих, промежуток
aside = total('Закреплённая врезка «Кто в этой истории» + 4 входа', [
    ('h2 «Кто в этой истории» 26/32 + 16', 48),
    ('строка «Бог …» 2 строки 16/24 + 8', 56),
    ('6 малых карточек лиц по ~116 px (одна в ряд, 368 px)', 6 * card),
    ('«ещё N» 44', 44),
    ('строка группы («звери, скот…») 2 строки + 8', 56),
    ('отступ', 24),
    ('2 ряда входов: плитка 172×129 (4:3) + подпись 24 + 16', 2 * (129 + 24 + 16)),
], 800 - 72 - 24)
print(f'\n  врезка выше окна (800 − шапка 72 − отступ 24 = 704 px) на {aside - 704} px')

# --- Страницы книг: высота сетки обложек
for book, verses, lo_d, hi_d in [('Бытие', 1533, 20, 14), ('1 Царств', 810, 20, 14),
                                 ('Марк', 678, 10, 5.4), ('Матфей', 1071, 10, 5.4), ('Деяния', 1006, 18, 14)]:
    lo, hi = verses / lo_d, verses / hi_d
    rows_l = (lo / 4, hi / 4); rows_p = (lo / 2, hi / 2)
    hl = [r * (cover_row + 32) for r in rows_l]; hp = [r * (ph_row + 16) for r in rows_p]
    print(f'{book}: стихов {verses}, историй {lo:.0f}–{hi:.0f}; ноутбук {hl[0]:.0f}–{hl[1]:.0f} px'
          f' ({hl[0]/704:.0f}–{hl[1]/704:.0f} экранов); телефон {hp[0]:.0f}–{hp[1]:.0f} px ({hp[0]/584:.0f}–{hp[1]/584:.0f} экранов)')

# --- Полоса 66 книг в колонке текста (7 колонок = 7·74 + 6·24 = 662 px)
W = 662
print(f'\nПолоса 66 книг в {W} px: равные клетки — {W/66:.1f} px на книгу.')
for b, v in [('Авд', 21), ('2 Ин', 13), ('Флм', 25), ('2 Пет', 61), ('Пс', 2527), ('Быт', 1533)]:
    print(f'  по числу стихов: {b} — {W*v/31170:.2f} px')
