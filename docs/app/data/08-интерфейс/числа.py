#!/usr/bin/env python3
"""Рецензия интерфейса на 08 «Дизайн-система»: проверочные числа.

Запуск из корня: python3 -I docs/app/data/08-интерфейс/числа.py
Шрифтов в проекте нет, поэтому ширина текста — оценка по средней ширине знака,
которую 08 сам измерил (приложение А, ч. 5б): Literata 400 — 0,5235 em на знак,
Golos Text 450 — 0,5206 em. Для насыщенности 600 берётся запас +5 % (оценка;
точный замер — скриптом 08 с папкой шрифтов).
"""
import glob, json, math, os, sys

ROOT = os.getcwd()
LIT = 10.47 / 20          # em на знак, Literata 400 (08, прил. А, ч. 5б)
GOL = 8.33 / 16           # em на знак, Golos Text 450
BOLD = 1.05               # запас на 600 (оценка)

def head(t):
    print(); print('=' * 78); print(t); print('=' * 78)

# ---------------------------------------------------------------- 1
head('1. Первый экран главного на телефоне: модель 11 (прил. А, § 13) с размерами 08')
# 11-числа.py: top = 56 шапка + 56 входы + 96 заголовок с эпиграфом + 40 строка Заветов + 40 ; head книги 48;
# ряд = 117 обложка + 44 подпись (2 × 22) + 18 адрес + 12 отступ
m11 = dict(top=56 + 56 + 96 + 40 + 40, head=48, cover=117, cap=2 * 22, addr=18, pad=12)
# 08: подпись под обложкой телефона 18/24, адрес Golos 15/20 (§ 3.3.2, § 7.3);
# переключатель слоя — «в строке под шапкой на главном экране» (§ 7.1): строка 48 + 8
m08 = dict(m11, cap=2 * 24, addr=20)
for name, m, extra in (('11 как записано', m11, 0), ('11 + размеры 08', m08, 0),
                       ('11 + размеры 08 + строка переключателя слоя', m08, 48 + 8)):
    end = m['top'] + extra + m['head'] + m['cover'] + m['cap'] + m['addr'] + m['pad']
    vis = []
    for vh in (640, 560, 500):
        vis.append(f"окно {vh}: {'видны 2 обложки с подписью' if end <= vh else 'ряд НЕ помещается'}")
    print(f"  {name}: первый ряд кончается на {end} px; " + '; '.join(vis))
print('  окна 560 и 500 — «проектирование на окно браузера» из 05 § 7.7 (панели Safari и Chrome)')

# ---------------------------------------------------------------- 2
head('2. Шапка нижнего листа (05 § 8.4; 08 § 7.10) при целях 48 px простого слоя')
parts = dict(ручка=16, имя=28, стих=24)
for layer, t in (('второй слой (кнопки 44)', 44), ('простой слой (кнопки 48)', 48)):
    print(f"  {layer}: {sum(parts.values())} + {t} = {sum(parts.values()) + t} px (08 и 05 пишут 112)")

# ---------------------------------------------------------------- 3
head('3. Обложка в каталоге по сетке 08 § 3.4 и строки подписи 40-знакового названия')
def grid(w):
    if w >= 1280: return 12, 64, 24
    if w >= 1024: return 12, 40, 24
    if w >= 600: return 8, 32, 16
    return 4, 16, 16
for w in (1440, 1280, 1024, 900, 768, 700, 600, 599, 414, 360, 320):
    n, mg, g = grid(w)
    content = min(w - 2 * mg, 1152)
    col = (content - (n - 1) * g) / n
    span = 3 if n == 12 else 2
    cw = span * col + (span - 1) * g
    kegel = 20 if w >= 600 else 18
    per_line = math.floor(cw / (kegel * LIT * BOLD))
    lines = math.ceil(40 / max(per_line, 1))
    print(f"  окно {w:4}: обложка {cw:5.0f} × {cw*3/4:4.0f}; подпись {kegel} px — около {per_line} знаков в строке, "
          f"название 40 знаков — {lines} строк(и)")
print('  Вывод: на 600–767 px обложка уже, чем на телефоне 360 (156 px), а кегль подписи больше.')

# ---------------------------------------------------------------- 4
head('4. Малая карточка на телефоне: 2 колонки (08 § 7.4) и имена без переноса (08 § 3.3.3)')
cols4 = (360 - 2 * 16 - 3 * 16) / 4
card = 2 * cols4 + 16
text_w = card - 32 - 8      # знак 32 px слева и промежуток 8
print(f"  карточка {card:.0f} px; место под имя после знака 32 и промежутка 8 — {text_w:.0f} px")
names = []
for f in sorted(glob.glob(os.path.join(ROOT, 'base/actors/*.json'))):
    for it in json.load(open(f, encoding='utf-8')).get('items', []):
        for n in it.get('names', []):
            if n.get('type') == 'main' and n.get('form'):
                names.append(n['form'])
print(f"  основных имён в базе: {len(names)}")
w_char = 20 * LIT * BOLD
whole = sorted(names, key=len, reverse=True)
hy = sorted({p for n in names for p in n.split() if '-' in p}, key=len, reverse=True)
over_whole = [n for n in names if len(n) * w_char > text_w]
over_hy = [p for p in hy if len(p) * w_char > text_w]
over_word = sorted({p for n in names for p in n.split() if len(p) * w_char > text_w}, key=len, reverse=True)
print(f"  ширина знака Literata 600, 20 px — около {w_char:.1f} px; в {text_w:.0f} px помещается {int(text_w // w_char)} знаков")
print(f"  имён, которые целиком (nowrap «на имени», 08 § 3.3.3) шире места: {len(over_whole)} из {len(names)}; "
      f"самое длинное: «{whole[0]}» — около {len(whole[0]) * w_char:.0f} px")
print(f"  составных частей с дефисом шире места (nowrap «на части с дефисом», 07 § 6.3.2): {len(over_hy)}; "
      f"примеры: {', '.join(over_hy[:5])}")
print(f"  отдельных слов имён шире места даже без nowrap: {len(over_word)}; примеры: {', '.join(over_word[:6])}")

# ---------------------------------------------------------------- 5
head('5. Строка инструмента Времени (04 § 3.9) в одну строку: помещается ли')
btns = ['Жизни', 'События', 'Сравнить', 'Кто ещё жил тогда?', 'Раньше', 'Позже', 'Крупнее',
        'Мельче', 'Списком', 'География', '‹ Ной и потоп']
gw = 16 * GOL * BOLD
total = sum(len(b) * gw + 2 * 16 for b in btns) + 8 * (len(btns) - 1) + 24 * 3  # значки у 3 кнопок
for w, cont in ((1440, 1152), (1280, 1152), (1024, 944), (768, 704)):
    print(f"  окно {w}: нужно около {total:.0f} px, есть {cont} — {'помещается' if total <= cont else 'НЕ помещается'}")
print('  (Golos 600 16, поля кнопки по 16, промежуток 8; ярлык возврата 08 § 7.1 стоит в той же строке)')
icon = {'Раньше', 'Позже', 'Крупнее', 'Мельче'}
total2 = sum((48 if b in icon else len(b) * gw + 2 * 16) for b in btns) + 8 * (len(btns) - 1) + 24 * 3
print(f"  если «Раньше», «Позже», «Крупнее», «Мельче» — кнопки-значки 48 px (08 § 7.8): около {total2:.0f} px — "
      f"1280: {'помещается' if total2 <= 1152 else 'НЕ помещается'}; 1024: {'помещается' if total2 <= 944 else 'НЕ помещается'}")

# ---------------------------------------------------------------- 6
head('6. Вес первого экрана телефона и LCP на профиле 08 § 9.2 («медленная 4G»: 1,6 Мбит/с, 150 мс)')
bps = 1.6 * 1024 * 1024 / 8     # Lighthouse: 1 638,4 Кбит/с
for name, kb in (('весь первый экран телефона (08 § 9.3, оценка 705 КБ)', 705),
                 ('бюджет первого экрана телефона (768 КБ)', 768),
                 ('без индекса поиска и без курсива (705 − 200 − 65)', 705 - 200 - 65),
                 ('только код и шрифты Literata прямой + Golos (120 + 111 + 33)', 120 + 111 + 33)):
    t = kb * 1024 / bps
    print(f"  {name}: передача {t:.2f} с + задержки (3–4 круга × 0,15 с)")
print('  Порог LCP 2,5 с. Бюджет «первого экрана» больше, чем сеть профиля передаёт за 2,5 с:'
      f' {2.5 * bps / 1024:.0f} КБ без задержек.')

# ---------------------------------------------------------------- 7
head('7. Кадры: 08 § 9.1 «50 кадров/с на телефоне» и «кадров длиннее 16,7 мс — не больше 5 %»')
for fps in (60, 50):
    mean = 1000 / fps
    print(f"  {fps} кадров/с — средний кадр {mean:.1f} мс; при 50 к/с на экране 60 Гц "
          f"не меньше {(1 - 50/60) * 100:.0f} % обновлений пропущено" if fps == 50 else
          f"  {fps} кадров/с — средний кадр {mean:.1f} мс")
print('  Экраны 90 и 120 Гц: бюджет кадра 11,1 и 8,3 мс — правило «16,7 мс» о них молчит.')

# ---------------------------------------------------------------- 8
head('8. Малый образ Времени: значки эпох 24 px над клетками (04 § 7.5; 08 § 7.5.1)')
for w in (270, 320, 352):
    cell = (w - 12) / 16
    print(f"  {w} px: клетка {cell:.1f} px; история в двух эпохах — 2 клетки = {2*cell:.1f} px под два значка 24 px "
          f"(нужно 48 + промежуток) — {'помещается' if 2*cell >= 52 else 'значки НАЛЕЗАЮТ или уходят со своих клеток'}")

# ---------------------------------------------------------------- 9
head('9. Порог двойника 08 § 6.1 п. 5 и основной вид телефона по 03 § 7.10')
print('  08: телефон 360 × 640 — «рисунок»; 03 § 7.10: основной вид телефона — семейная страница '
      '(это двойник схемы, 03 § 6.5), схема — по кнопке «Схема» на любой ширине телефона.')
print('  Значит, для 03 правило 08 «не отнимает рисунок у телефона 360» не выполняется и не может быть проверено одним тестом.')

# ---------------------------------------------------------------- 10
head('10. Паспорт страницы истории (4 колонки) и малые образы 08 § 7.5 на ширинах двух колонок')
for w in (1440, 1280, 1100, 1024):
    n, mg, g = grid(w)
    content = min(w - 2 * mg, 1152)
    col = (content - (n - 1) * g) / n
    passport = 4 * col + 3 * g
    text = 7 * col + 6 * g
    pair = 172 + 172 + g
    print(f"  окно {w}: паспорт {passport:.0f} px; География + Генеалогия рядом {pair} px — "
          f"{'помещается' if pair <= passport + 0.5 else 'НЕ помещается'}; Время 352 px — "
          f"{'помещается' if 352 <= passport + 0.5 else 'НЕ помещается'}; колонка текста {text:.0f} px — "
          f"около {text / (20 * LIT):.0f} знаков при 20 px")
print()
print('Готово.')
